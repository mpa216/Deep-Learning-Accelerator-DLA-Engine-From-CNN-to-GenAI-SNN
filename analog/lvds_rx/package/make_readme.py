#!/usr/bin/env python3
"""make_readme.py -- T12: package/README.md from the gate results (host or container).
Reads results/gates.json (full tier), results/gates_layout.json, results/post_layout/tbl.json, results/sizing.json,
package/pin_caps.json, package/KNOWN_LIMITS.json, package/checks/report.json, spec/pins.yaml, spec/spec.yaml."""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "flow"))
import common as C  # noqa: E402


def j(rel):
    p = os.path.join(ROOT, rel)
    return json.load(open(p)) if os.path.exists(p) else None


def check(g, gid, metric, kind="per_run", where=None):
    for c in (g.get("gates", {}).get(gid, {}).get("checks") or []):
        if c.get("metric") == metric and c.get("kind") == kind and (where is None or c.get("where") == where):
            return c
    return None


def fmt(v, scale=1.0, f="%.3g"):
    return "-" if v is None else f % (v * scale)


def main():
    g = j("results/gates.json") or {}
    gl = j("results/gates_layout.json") or {}
    tbl = j("results/post_layout/tbl.json") or {}
    sz = j("results/sizing.json") or {}
    caps = j("package/pin_caps.json") or {}
    lim = j("package/KNOWN_LIMITS.json") or {}
    chk = j("package/checks/report.json") or {}
    pins = C.load_yaml("spec/pins.yaml")
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    L = ["# lvds_rx_x3: three-lane LVDS receiver hard macro (gf180mcuD, 3.3 V)", "",
         "GENERATED by `package/make_readme.py`; do not edit by hand. Source commit `%s` (branch `lvds-rx`)." % head, "",
         "Three LVDS receiver lanes (CLK, D0, D1) with one shared bias block, 100 Mb/s NRZ per lane (margin eye at 200 Mb/s), "
         "input common mode 0.05-2.35 V, 3.3 V CMOS outputs, EN power-down. Macro 650 x 192.1 um (core 600 x 142.1 um "
         "plus a 25 um margin), internals on Metal1-Metal3 only. Learning project: nothing here is part of the A56 submission.", "",
         "## Status", ""]
    summ = g.get("summary", {})
    L += ["- Pre-layout regression (full tier, every corner and Monte Carlo of `spec/gates.yaml`): %s, gates %s, generated %s." % (
        "GREEN" if g.get("green") else "NOT GREEN", summ, g.get("generated", "-")),
          "- Layout sign-off (gate LAYOUT, PLAN_V2 6.4 steps 1-6): %s." % (gl.get("gates", {}).get("LAYOUT", {}).get("status", "-")),
          "- Post-layout re-simulation (gate TBL, extracted RC macro against the pre-layout netlist, 30 %% of margin): %s, %s pairs, "
          "largest use of margin %s, D-012 condition %s." % (tbl.get("status", "-"), tbl.get("summary", {}).get("pairs", "-"),
                                                            fmt(tbl.get("summary", {}).get("margin_used_max")),
                                                            "met" if tbl.get("d012", {}).get("ok") else "-"),
          "- Package checks (`package/checks/run_checks.py`): %s." % ("PASS" if chk.get("all_ok") else "-"), ""]
    L += ["## Pins", "", "| Pin | Dir | Layer | Edge | x (um) | Note |", "|---|---|---|---|---|---|"]
    for p in pins["pins"]:
        note = {"power": "3.3 V supply, Metal3 straps across the macro", "ground": "ground, Metal3 straps across the macro"}.get(p["use"], "")
        if p["name"] == "EN":
            note = "1 = on; 0 = bias off, outputs LOW. Hold LOW until VDD >= 2.0 V (D-008)"
        elif p["name"].endswith("_O"):
            note = "3.3 V CMOS, = (P > N); asynchronous: capture through a synchronizer"
        elif p.get("analog"):
            note = "pad side, through the secondary ESD (151 ohm + clamps) to the receiver"
        L.append("| %s | %s | %s | %s | %s | %s |" % (p["name"], p["dir"], p["layer"], p["side"], p.get("x_um", "-"), note))
    L += ["", "Pad-slot x positions are inferred (spec/pins.yaml, unverified with the organizers)."]
    if caps.get("corners"):
        L += ["", "Input capacitance (extracted macro, AC at 100 MHz, `package/pin_caps.json`):", "",
              "| Corner | RXk_P / RXk_N (fF) | EN (fF) |", "|---|---|---|"]
        for c, v in caps["corners"].items():
            rx = [v[k] for k in v if k.startswith("RX")]
            L.append("| %s | %.0f .. %.0f | %.0f |" % (c, min(rx) * 1e15, max(rx) * 1e15, v["EN"] * 1e15))
    # specs met
    L += ["", "## Specifications met (pre-layout full tier, worst over the scope)", "", "| Gate | Scope | Runs | Check | Worst | Limit | Status |",
          "|---|---|---|---|---|---|---|"]
    for gid, r in (g.get("gates") or {}).items():
        for c in r.get("checks", []):
            if c.get("kind") == "report":
                continue
            name = c["metric"] + (" over %s" % c["over"] if c.get("kind") == "spread" else "")
            if c.get("where"):
                name += " (" + ", ".join("%s=%s" % kv for kv in c["where"].items()) + ")"
            L.append("| %s | %s | %s | %s | %s | %s | %s |" % (gid, r.get("phase", ""), "%s/%s" % (r.get("actual_runs"), r.get("expected_runs")),
                                                            name, fmt(c.get("worst")), c.get("limit", "-"), c.get("status")))
    off = check(g, "TB3_off", "vos_v", kind="mc_offset_window")
    if off:
        L += ["", "Monte Carlo input offset (TB3_off, N = %s per corner and VIC, worst5 x 3 VIC): worst group mean %s mV, sigma %s mV, "
              "window total %s mV against %s." % (off.get("samples"), fmt(off.get("mean"), 1e3), fmt(off.get("sigma"), 1e3),
                                                 fmt(off.get("worst"), 1e3), off.get("limit"))]
    if sz:
        L += ["", "Supply current (sizing tally, tt): %s; sigma_total of the offset budget %.2f mV." % (
            {k: "%.0f uA lane / %.0f uA bias" % (v["i_lane_uA"], v["i_bias_uA"]) for k, v in sz.get("tally", {}).items() if k == "tt_27c_3v30"},
            sz.get("sigma_total_mV", float("nan")))]
    L += ["", "Corner sets (sim/harness/corners.py): full45 = tt/ss/ff/fs/sf x -40/27/125 C x 3.0/3.3/3.6 V; worst5 = tt 27 C 3.3 V, "
          "ss 125 C 3.0 V, ff -40 C 3.6 V, fs and sf 27 C 3.3 V; eye15 = 5 processes x (-40 C 3.6 V, 27 C 3.3 V, 125 C 3.0 V).",
          "", "## Integration", "",
          "- `lef/lvds_rx_x3.lef`: CLASS BLOCK, SIZE 650 x 192.1, OBS on Nwell and Metal1-Metal3; route over the macro on Metal4/Metal5 "
          "only. VDD / VSS are the Metal3 straps (connect the core grid with Metal4 stripes and via3). RXk_P / RXk_N on the top edge "
          "(pad side), EN and RXk_O on the bottom edge (core side).",
          "- `lib/`: one Liberty file per corner (tt_025C_3v30, ss_125C_3v00, ff_n40C_3v60), blackbox without timing arcs; RXk_O "
          "max_capacitance 30 fF and max_transition 1 ns (the verified load and edge).",
          "- `verilog/lvds_rx_x3.v`: `SYNTHESIS` blackbox, otherwise a behavioural model (v0: an idle input holds the last value). "
          "Do not tie the power pins in RTL; drive the pad pins through wires in testbenches.",
          "- `spice/lvds_rx_x3.spice`: the LVS reference the layout matched (gf180mcuD device names); `gds/lvds_rx_x3.gds`: DBU 0.001.",
          "- Keep EN LOW until VDD >= 2.0 V; capture RXk_O through synchronizers (asynchronous to the core clock).", "",
          "## Known limits (`KNOWN_LIMITS.json`)", ""]
    for k, v in lim.items():
        if k in ("generated_by", "decisions_on_record"):
            continue
        L.append("- **%s**: %s" % (k, v))
    L += ["", "## What was NOT touched", "",
          "Nothing under `macros/`, `rtl/`, `info.yaml`, `lvs_config.json` or the padframe, and nothing on `main`: this package lives "
          "in `analog/lvds_rx/package/` on the local branch `lvds-rx`. Chip integration (PLAN_V2 P7/P8) is owner-gated and not done.",
          "", "## Regenerate", "", "```", "tools/cx python3 package/pin_caps.py          # pin capacitance from the extracted macro",
          "tools/cx python3 package/make_package.py      # gds, lef, lib, spice, verilog, tb, KNOWN_LIMITS",
          "tools/cx python3 package/checks/run_checks.py # PLAN_V2 section 7 tests -> checks/report.json",
          "python3 package/make_readme.py                # this file", "```", ""]
    with open(os.path.join(HERE, "README.md"), "w") as f:
        f.write("\n".join(L))
    print("README.md written,", len(L), "lines")


if __name__ == "__main__":
    main()
