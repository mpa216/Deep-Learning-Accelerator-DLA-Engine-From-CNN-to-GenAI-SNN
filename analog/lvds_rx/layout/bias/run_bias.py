#!/usr/bin/env python3
"""run_bias.py [--stage place|rails|route] [--nok]   build the bias block and check it.  Run INSIDE the container:

  docker exec apic_headless bash /foss/designs/.claude/worktrees/lvds-rx/analog/lvds_rx/tools/cx python3 layout/bias/run_bias.py [--stage S] [--nok]

  --stage place | rails   partial build (cell bias_<stage>): Magic DRC (.mag and GDS read-back), KLayout foundry deck main +
                          antenna, picture.  No LVS (nets still open).
  --stage route (default) the finished block, cell lvds_bias: check.run_cell (self-check, DRC, strict LVS, finger read-back,
                          negative controls incl. a Metal3 bridge), the reference-file LVS against lvds_bias of
                          netlist/lvds_rx_lvs_ref.spice, and check_via_arrays.py.
  --nok                   skip the KLayout deck (fast loop; never a sign-off)
Work files: .scratch/t10/work/<cell>/.  Results: layout/bias/results/.
"""
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
LAYOUT = os.path.dirname(HERE)
ROOT = os.path.dirname(LAYOUT)
sys.path.insert(0, LAYOUT)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(LAYOUT, "lane"))

from lib import check                                 # noqa: E402
import bias                                            # noqa: E402
import run_lane                                        # noqa: E402

RESULTS = os.path.join(HERE, "results")
OUT = os.path.join(ROOT, ".scratch", "t10", "work")
CO6 = run_lane.CO6


def partial(stage, nok):
    name = f"bias_{stage}"
    t0 = time.time()
    B = bias.build(stage, name=name)
    wd = os.path.join(OUT, name)
    os.makedirs(RESULTS, exist_ok=True)
    res = dict(cell=name, stage=stage, steps={}, started=time.strftime("%Y-%m-%d %H:%M:%S"), box_um=[bias.W_B, B.height],
               python_build_s=round(time.time() - t0, 1))
    b = check.build(B.blk, wd)
    res["steps"]["build"] = dict(ok=not b["errors"] and not b["genbbox_mismatch"], errors=b["errors"], genbbox_mismatch=b["genbbox_mismatch"])
    gds = b["gds"]
    if os.path.exists(gds):
        res["steps"]["metal_cap"] = check.metal_cap(B.blk, gds)
        d1 = check.magic_drc(name, wd, wd, "mag", CO6)
        d2 = check.magic_drc(name, gds, wd, "gds", CO6)
        res["steps"]["magic_drc"] = dict(ok=(d1["effective"] == 0 and d2["effective"] == 0), mag=d1, gds_readback=d2, allow=list(CO6))
        if not nok:
            k = check.klayout_drc(gds, name, os.path.join(wd, "klayout"))
            k["ok"] = bool(k["dbu_ok"] and k["main"] == 0 and k.get("antenna") == 0 and k["main_lyrdb_files"] > 0)
            res["steps"]["klayout"] = k
        png = os.path.join(RESULTS, name + ".png")
        check.sh(["python3", os.path.join(LAYOUT, "lib", "render.py"), gds, name, png])
        res["steps"]["render"] = dict(ok=os.path.exists(png))
    res["all_ok"] = all(s.get("ok", False) for s in res["steps"].values())
    res["wall_s"] = round(time.time() - t0, 1)
    with open(os.path.join(RESULTS, name + ".json"), "w") as f:
        json.dump(res, f, indent=1, default=str)
    print(name, "OK" if res["all_ok"] else "NOT OK", f"{res['wall_s']} s")
    for k, s in res["steps"].items():
        print("   %-10s %s %s" % (k, "ok" if s.get("ok") else "NOT OK", "" if s.get("ok") else str(s)[:1500]))
    return res["all_ok"]


def full(nok):
    t0 = time.time()
    B = bias.build("route")
    sch = bias.schematic(B)
    os.makedirs(RESULTS, exist_ok=True)
    with open(os.path.join(RESULTS, bias.CELL + ".spice"), "w") as f:
        f.write("* LVS schematic of the bias block: subckt lvds_bias of netlist/lvds_rx_lvs_ref.spice flattened + the layout's dummies.\n"
                "* GENERATED by layout/bias/bias.py (schematic) -- do not edit by hand.\n" + sch)
    r = check.run_cell(B.blk, sch, OUT, RESULTS, klayout=not nok, cut_net="VBN", cut_kind="route", magic_allow=CO6, bridge_kind="route")
    r["python_build_s"] = round(time.time() - t0 - r["wall_s"], 1)
    wd = os.path.join(OUT, bias.CELL)
    gds = os.path.join(wd, bias.CELL + ".gds")
    r["steps"]["lvs_reference"] = run_lane.reference_lvs_text(bias.CELL, bias.schematic(B, dummies=False), wd)
    r["steps"]["via_arrays"] = check.via_arrays(gds, bias.CELL, wd)
    run_lane.verdict(r)
    r["wall_s"] = round(time.time() - t0, 1)
    r["box_um"] = [bias.W_B, B.height]
    r["schematic"] = B.schem_counts
    r["routes"] = B.R.summary()
    r["klayout_skipped"] = bool(nok)
    with open(os.path.join(RESULTS, bias.CELL + ".json"), "w") as f:
        json.dump(r, f, indent=1, default=str)
    print(bias.CELL, r["verdict"], f"{r['wall_s']} s", "(KLayout deck skipped: not a sign-off)" if nok else "")
    for k, s in r["steps"].items():
        print("   %-16s %s %s" % (k, "ok" if s.get("ok") else "NOT OK", "" if s.get("ok") else str(s)[:1800]))
    return bool(r["all_ok"])


def main(args):
    nok = "--nok" in args
    stage = args[args.index("--stage") + 1] if "--stage" in args else "route"
    if stage != "route":
        return 0 if partial(stage, nok) else 1
    return 0 if full(nok) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
