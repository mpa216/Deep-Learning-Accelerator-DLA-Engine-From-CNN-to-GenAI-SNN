#!/usr/bin/env python3
"""run_macro.py [--stage drc] [--nok]   build the macro lvds_rx_x3 (three lanes + bias block as subcells) and check it.
Run INSIDE the container:

  docker exec apic_headless bash /foss/designs/.claude/worktrees/lvds-rx/analog/lvds_rx/tools/cx python3 layout/macro/run_macro.py [--stage drc] [--nok]

Steps (PLAN_V2 6.4 on the macro): build (lane, bias block, macro in ONE work directory, so Magic finds the subcells there);
Magic DRC on the .mag and on the GDS read back; KLayout foundry deck main + antenna (flat run over the hierarchy);
check_via_arrays.py; then (not with --stage drc) hierarchical extraction and strict Netgen LVS against the hierarchical
schematic (lvds_lane and lvds_bias with their dummies + lvds_rx_x3 of the reference file), the top level also against the
frozen reference file, negative controls (wrong W, a cut fill between lanes, a top-level bridge, a DRC sliver), antenna
without the ESD diodes, picture.  --nok skips the KLayout deck (never a sign-off).
Work files: .scratch/t10/work/lvds_rx_x3/.  Results: layout/macro/results/.
"""
import json
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
LAYOUT = os.path.dirname(HERE)
ROOT = os.path.dirname(LAYOUT)
sys.path.insert(0, LAYOUT)
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(LAYOUT, "lane"))
sys.path.insert(0, os.path.join(LAYOUT, "bias"))

from lib import check                                 # noqa: E402
from lib.selfcheck import parse_ext_devices           # noqa: E402
import lane                                            # noqa: E402
import bias                                            # noqa: E402
import macro                                           # noqa: E402
import run_lane                                        # noqa: E402

RESULTS = os.path.join(HERE, "results")
OUT = os.path.join(ROOT, ".scratch", "t10", "work")
CO6 = run_lane.CO6


def run(stage, nok):
    t0 = time.time()
    L, B = lane.build("route"), bias.build("route")
    M = macro.build(L, B)
    name = macro.CELL
    wd = os.path.join(OUT, name)
    os.makedirs(RESULTS, exist_ok=True)
    r = dict(cell=name, steps={}, started=time.strftime("%Y-%m-%d %H:%M:%S"), fixed_bbox_um=list(M.fixed_bbox), core_um=list(M.core),
             y0=M.y0, instances=M.blk.instances, python_build_s=round(time.time() - t0, 1))
    # ---- 1 build: subcells first (the first build cleans the directory), then the macro
    bl = check.build(L.blk, wd)
    bb = check.build(B.blk, wd, clean=False)
    bm = check.build(M.blk, wd, clean=False)
    errs = bl["errors"] + bb["errors"] + bm["errors"]
    r["steps"]["build"] = dict(ok=not errs and not (bl["genbbox_mismatch"] or bb["genbbox_mismatch"]), errors=errs[:5])
    gds = bm["gds"]
    if not os.path.exists(gds):
        r["verdict"] = "FAIL (no GDS)"
        return _write(r, t0)
    r["steps"]["metal_cap"] = check.metal_cap(M.blk, gds)
    # ---- 2 Magic DRC (the .mag of all three cells sit in wd)
    d1 = check.magic_drc(name, wd, wd, "mag", CO6, flat=True)
    d2 = check.magic_drc(name, gds, wd, "gds", CO6, flat=True)
    r["steps"]["magic_drc"] = dict(ok=(d1["effective"] == 0 and d2["effective"] == 0), mag=d1, gds_readback=d2, allow=list(CO6))
    # ---- 3 KLayout foundry deck, 4 via arrays
    if not nok:
        k = check.klayout_drc(gds, name, os.path.join(wd, "klayout"))
        k["ok"] = bool(k["dbu_ok"] and k["main"] == 0 and k.get("antenna") == 0 and k["main_lyrdb_files"] > 0 and k.get("antenna_lyrdb_files", 0) > 0)
        r["steps"]["klayout"] = k
    r["steps"]["via_arrays"] = check.via_arrays(gds, name, wd)
    png = os.path.join(RESULTS, name + ".png")
    check.sh(["python3", os.path.join(LAYOUT, "lib", "render.py"), gds, name, png])
    r["steps"]["render"] = dict(ok=os.path.exists(png))
    if stage == "drc":
        return _write(r, t0)
    # ---- 5 LVS, hierarchical: lvds_lane and lvds_bias are compared cell by cell, then the top level
    sch = macro.schematic(M)
    with open(os.path.join(RESULTS, name + ".spice"), "w") as f:
        f.write("* LVS schematic of the macro: lvds_lane and lvds_bias (the reference flattened + the layout's dummies) and\n"
                "* lvds_rx_x3 as in netlist/lvds_rx_lvs_ref.spice.  GENERATED by layout/macro/macro.py -- do not edit by hand.\n" + sch)
    ex = check.extract(name, gds, wd, "lvs")
    lv = check.netgen_lvs(name, ex["spice"], sch, wd, "good")
    lv["ok"] = lv["clean"]
    lv["extraction_warnings"] = ex["warnings"]
    r["steps"]["lvs"] = lv
    # the same netlist without dummies against lvds_rx_x3 of the frozen reference file (Netgen flattens the reference's
    # lane sub-blocks; the bias and the top level compare as they are)
    nod = lane.schematic(L, dummies=False) + bias.schematic(B, dummies=False) + sch[sch.index(".subckt lvds_rx_x3"):]
    r["steps"]["lvs_reference"] = run_lane.reference_lvs_text(name, nod, wd)
    # self-check and finger read-back of the two subcells, from the macro's own extraction
    exd = os.path.dirname(ex["ext"])
    sub = {}
    for cell, blk in ((lane.CELL, L.blk), (bias.CELL, B.blk)):
        e = os.path.join(exd, cell + ".ext")
        try:
            obs = check.selfcheck(blk, e)
            sc = dict(ok=True, **{k: v for k, v in obs.items() if k != "mos"})
        except Exception as err:                                  # noqa: BLE001
            sc = dict(ok=False, error=str(err))
        fb = check.finger_readback(blk, e)
        sub[cell] = dict(ok=bool(sc["ok"] and fb["ok"]), selfcheck=sc, finger_rows=len(fb["rows"]), fingers=sum(x["n_read"] for x in fb["rows"]),
                         readback_ok=fb["ok"])
    r["steps"]["subcells"] = dict(ok=all(v["ok"] for v in sub.values()), **sub)
    # ---- negative controls on the top level
    neg = {}
    nl = check.netgen_lvs(name, ex["spice"], _wrong_w(sch), wd, "badw")
    neg["wrong_W"] = dict(detected=not nl["clean"], why=nl.get("why"))
    fill = [f for f in M.fills if f[1] == "vbn"][0]                # the vbn fill between lane 0 and lane 1
    shp = type("S", (), dict(layer="m3", kind="fill", x1=fill[2][0], y1=fill[2][1], x2=fill[2][2], y2=fill[2][3], net="vbn"))()
    cg = os.path.join(wd, "cut.gds")
    check.cut_wire(gds, cg, shp)
    exc = check.extract(name, cg, wd, "cut")
    lc = check.netgen_lvs(name, exc["spice"], sch, wd, "cut")
    neg["cut_wire"] = dict(detected=not lc["clean"], net="vbn", at=list(fill[2]), why=lc.get("why"))
    pk = check.pick_bridge(M.blk, kind="route")
    if pk is None:
        neg["bridge"] = dict(detected=False, error="no bridge site found")
    else:
        bg = os.path.join(wd, "bridge.gds")
        check.add_rect(gds, bg, pk["layer"], pk["rect"])
        exb = check.extract(name, bg, wd, "bridge")
        lb = check.netgen_lvs(name, exb["spice"], sch, wd, "bridge")
        neg["bridge"] = dict(detected=not lb["clean"], nets=pk["nets"], at=list(pk["rect"]), gap_um=pk["gap_um"], why=lb.get("why"))
    sg = os.path.join(wd, "sliver.gds")
    check.add_sliver(gds, sg)
    ms = check.magic_drc(name, sg, wd, "sliver", flat=True)
    neg["sliver_magic"] = dict(detected=(ms["total"] or 0) > 0, count=ms["total"])
    if not nok:
        ks = check.klayout_drc(sg, name, os.path.join(wd, "klayout_sliver"), antenna=False)
        neg["sliver_klayout"] = dict(detected=ks["main"] > 0, count=ks["main"], rules=ks["main_rules"])
    r["steps"]["negctl"] = dict(ok=all(v["detected"] for v in neg.values()), **neg)
    # ---- antenna without the ESD diodes (PLAN_V2 6.4 step 3)
    if not nok:
        ng = os.path.join(wd, "no_esd_diodes.gds")
        rec = check.strip_diodes(gds, ng)
        want_n = len(L.blk.expect_dio)
        want_a = round(sum(e["w"] * e["l"] for e in L.blk.expect_dio), 3)
        exn = check.extract(name, ng, wd, "nodiode")
        left = sum(1 for f in os.listdir(os.path.dirname(exn["ext"])) if f.endswith(".ext")
                   for d in parse_ext_devices(os.path.join(os.path.dirname(exn["ext"]), f)) if d["model"].startswith("diode"))
        k = check.klayout_drc(ng, name, os.path.join(wd, "klayout_no_esd"), antenna=True, main=False)
        r["steps"]["antenna_no_esd"] = dict(ok=bool(rec["plates"] == want_n and abs(rec["plate_area_um2"] - want_a) < 0.01 and left == 0
                                                    and k["dbu_ok"] and k["antenna"] == 0 and k["antenna_lyrdb_files"] > 0),
                                            removed=rec, expected_plates_per_lane_cell=want_n, diodes_extracted_after=left,
                                            antenna=k["antenna"], antenna_rules=k["antenna_rules"])
    r["schematic_lines"] = len(sch.splitlines())
    # ---- 6 PEX (piece D): C on all nets and RC on all nets, flat, ports in the reference order; smoke test in ngspice
    r["steps"]["pex"] = pex(L, B, M, wd, gds, lv["out"])
    run_lane.verdict(r)
    r["layout_json"] = layout_json(r, L, B, M)
    return _write(r, t0)


def layout_json(r, L, B, M):
    """results/layout.json for gate LAYOUT of spec/gates.yaml (phase layout).  drc_magic_total is Magic's count on the GDS
    read back (the deliverable); the .mag count and its allow-list (CO.6 on the L = 0.28 contact bars, stricter than the
    foundry deck, T8) are recorded beside it.  m1_m3_max_shape_um is the largest painted Metal1-3 piece of the three cells."""
    s = r["steps"]
    pieces = [max(op[4] - op[2], op[5] - op[3]) for blk in (L.blk, B.blk, M.blk) for op in blk.ops
              if op[0] == "r" and op[1] in ("m1", "m2", "m3")]
    caps = s["pex"]["caps"]
    asym = max(max(v["RX"]["mismatch_pct"], v["gate"]["mismatch_pct"]) for k, v in caps.items() if k.startswith("lane"))
    k = s.get("klayout", {})
    out = dict(
        generated=time.strftime("%Y-%m-%d %H:%M:%S"), source="layout/macro/run_macro.py (cell lvds_rx_x3, T10)", verdict=r.get("verdict"),
        selfcheck_failed=sum(0 if v["selfcheck"]["ok"] else 1 for c, v in s["subcells"].items() if isinstance(v, dict) and "selfcheck" in v),
        drc_magic_total=s["magic_drc"]["gds_readback"]["total"],
        drc_magic_mag_flat_total=s["magic_drc"]["mag"]["total"], drc_magic_mag_allowed=s["magic_drc"]["mag"]["allowed"],
        drc_magic_allow_list=s["magic_drc"]["allow"],
        klayout_dbu_um=k.get("dbu"), klayout_main_total=k.get("main"), klayout_antenna_total=k.get("antenna"),
        klayout_antenna_no_esd_total=s.get("antenna_no_esd", {}).get("antenna"),
        via_array_total=s["via_arrays"]["violations"],
        lvs_match_unique=int(bool(s["lvs"]["match_line"] and s["lvs"]["final_unique"])),
        lvs_property_errors=int(bool(s["lvs"]["property_errors"])), lvs_port_errors=int(bool(s["lvs"]["port_errors"])),
        lvs_counts_equal=int(bool(s["lvs"]["counts_equal"])), lvs_reference_clean=int(bool(s["lvs_reference"]["clean"])),
        negctl_all_fail=int(bool(s["negctl"]["ok"])),
        finger_order_ok=int(all(v["readback_ok"] for c, v in s["subcells"].items() if isinstance(v, dict) and "readback_ok" in v)),
        m1_m3_max_shape_um=round(max(pieces), 3),
        pn_input_cap_asym_pct=asym,
        fixed_bbox_um=r["fixed_bbox_um"], core_um=r["core_um"])
    path = os.path.join(ROOT, "results", "layout.json")
    with open(path, "w") as f:
        json.dump(out, f, indent=1)
    return os.path.relpath(path, ROOT)


DELIV = os.path.join(ROOT, "results", "layout")          # PLAN_V2 T10 outputs: results/layout/*


def _ports(cell):
    sys.path.insert(0, os.path.join(ROOT, "netlist"))
    import lvds_circuit as C
    return list(C.SUBCKTS[cell][0])


def pex_file(src, cell, out, note, gds_sha):
    """The extracted netlist with its subckt renamed to `cell` and the ports in the order of subckt `cell` of the reference
    (testbenches connect by position; Magic writes its own order).  The two port lists must hold the same names."""
    import re
    txt = open(src).read()
    m = re.search(r"^\.subckt (\S+)([^\n]*)\n((?:\+[^\n]*\n)*)", txt, re.M)
    name = m.group(1)
    got = (m.group(2) + " " + " ".join(l[1:] for l in m.group(3).splitlines())).split()
    want = _ports(cell)
    if sorted(got) != sorted(want):
        raise ValueError(f"pex_file({cell}): extracted ports {got} != reference ports {want}")
    txt = txt[:m.start()] + f".subckt {cell} {' '.join(want)}\n" + txt[m.end():]
    txt = re.sub(r"^\.ends\b.*$", f".ends {cell}", txt, flags=re.M)
    head = (f"* {cell}: {note}\n* GENERATED by layout/macro/run_macro.py (T10) from a GDS with sha256 {gds_sha} -- do not edit by hand.\n"
            f"* Ports in the order of subckt {cell} of netlist/lvds_rx_lvs_ref.spice (Magic's own order was: {' '.join(got)}).\n")
    with open(out, "w") as f:
        f.write(head + txt)
    n = {k: len(re.findall(rf"^{k}", txt, re.M)) for k in ("X", "C", "R", "D")}
    return dict(file=os.path.relpath(out, ROOT), magic_port_order=got, elements=n, bytes=len(txt))


def smoke(wd, decks):
    """ngspice .op of the macro (typical corner, 27 C, 3.3 V, harness header) for each netlist variant: lanes 0 and 2 at
    VID +100 mV, lane 1 at -100 mV, VIC 1.2 V, EN high.  Returns the three outputs and the supply current per variant."""
    import re
    sys.path.insert(0, os.path.join(ROOT, "sim"))
    from harness.corners import Corner
    hdr = Corner("tt", 27, 3.3).header(mc="none")
    stim = ("VDD VDD 0 3.3\nVSS VSS 0 0\nVEN EN 0 3.3\n"
            "V0P RX0_P 0 1.25\nV0N RX0_N 0 1.15\nV1P RX1_P 0 1.15\nV1N RX1_N 0 1.25\nV2P RX2_P 0 1.25\nV2N RX2_N 0 1.15\n"
            "XM VDD VSS RX0_P RX0_N RX1_P RX1_N RX2_P RX2_N EN RX0_O RX1_O RX2_O lvds_rx_x3\n")
    out = {}
    for label, incs in decks.items():
        deck = os.path.join(wd, f"smoke_{label}.spice")
        with open(deck, "w") as f:
            f.write(f"* T10 smoke test of the macro netlist variant '{label}'\n" + hdr + "".join(f".include {p}\n" for p in incs) + stim +
                    ".control\nop\nprint v(rx0_o) v(rx1_o) v(rx2_o) i(vdd)\n.endc\n.end\n")
        t1 = time.time()
        rc, txt, _ = check.sh(["ngspice", "-b", deck], cwd=wd, timeout=1200)
        vals = {k.lower(): float(v) for k, v in re.findall(r"^(v\(rx\d_o\)|i\(vdd\))\s*=\s*([-+0-9.eE]+)", txt, re.M)}
        out[label] = dict(rc=rc, wall_s=round(time.time() - t1, 1), values=vals,
                          errors=[l for l in txt.splitlines() if re.search(r"(?i)error|singular|failed", l)][:3])
    return out


def pex(L, B, M, wd, gds, lvs_out):
    import hashlib
    import shutil
    os.makedirs(DELIV, exist_ok=True)
    res, files = {}, {}
    cells = ((macro.CELL, gds, True), (lane.CELL, os.path.join(wd, lane.CELL + ".gds"), False),
             (bias.CELL, os.path.join(wd, bias.CELL + ".gds"), False))
    import re
    rep = {}
    for cell, g, flat in cells:
        sha = hashlib.sha256(open(g, "rb").read()).hexdigest()
        raw = {}
        for mode, note in (("pex_c", "parasitic C on all nets (coupling and to substrate, cthresh 0)"),
                           ("pex_rc", "parasitic R (extresist, tolerance 10) on all nets; C from the C-coupled extraction "
                                      "(check.rc_repair, T11: Magic 8.3.636 extresist counts every coupling twice)")):
            ex = check.extract(cell, g, wd, f"{mode}_{cell}", mode=mode, flat=flat)
            raw[mode] = ex
            src = ex["spice"]
            if mode == "pex_rc":       # T11: the RC netlist's capacitance repaired from the C-coupled one of the same layout
                src = ex["spice"].replace(".lay.spice", ".repaired.spice")
                rep[cell] = check.rc_repair(raw["pex_c"]["spice"], ex["spice"], src,
                                            key=lambda n: check.flat_base(re.sub(r"\.(n|t)\d+$", "", n)))
                rep[cell].pop("out")
            files[f"{cell}.{mode}"] = pex_file(src, cell, os.path.join(DELIV, f"{cell}.{mode}.spice"),
                                               note + (" (flat copy of the hierarchy)" if flat else ""), sha)
            files[f"{cell}.{mode}"]["extract_s"] = ex["wall_s"]
    res["netlists"] = files
    res["rc_repair"] = rep
    # capacitance summary of the macro (flat C netlist): RX pins and the lanes' gate nets, outputs, enable
    caps = check.net_caps(os.path.join(ROOT, files[f"{macro.CELL}.pex_c"]["file"]), key=check.flat_base)
    c = {n: round(v["total_fF"], 3) for n, v in caps.items()}

    def pair(a, b):
        ca, cb = c.get(a, 0.0), c.get(b, 0.0)
        return dict(fF=[ca, cb], mismatch_pct=round(200 * abs(ca - cb) / (ca + cb), 3) if ca + cb else None)
    res["caps"] = {f"lane{k}": dict(RX=pair(f"RX{k}_P", f"RX{k}_N"), gate=pair(f"lvds_lane_{k}.gp", f"lvds_lane_{k}.gn"))
                   for k in range(3)}
    res["caps"]["outputs_fF"] = {f"RX{k}_O": c.get(f"RX{k}_O") for k in range(3)}
    res["caps"]["EN_fF"] = c.get("EN")
    # smoke test: pre-layout netlist vs the two extracted ones
    res["smoke"] = smoke(wd, {
        "prelayout": [os.path.join(ROOT, "sizing", "sizes.spice"), os.path.join(ROOT, "netlist", "lvds_rx_core.spice")],
        "pex_c": [os.path.join(DELIV, f"{macro.CELL}.pex_c.spice")],
        "pex_rc": [os.path.join(DELIV, f"{macro.CELL}.pex_rc.spice")]})
    pre = res["smoke"]["prelayout"]["values"]

    def level(v):
        return None if v is None else (1 if v > 2.5 else 0 if v < 0.8 else "x")
    ok = all(s["rc"] == 0 and not s["errors"] and len(s["values"]) == 4 for s in res["smoke"].values())
    for lab, s in res["smoke"].items():
        s["levels"] = [level(s["values"].get(f"v(rx{k}_o)")) for k in range(3)]
        s["idd_vs_prelayout_pct"] = (round(100 * (s["values"]["i(vdd)"] / pre["i(vdd)"] - 1), 2)
                                     if "i(vdd)" in s["values"] and pre.get("i(vdd)") else None)
    lv0 = res["smoke"]["prelayout"]["levels"]
    ok = ok and lv0[0] == lv0[2] != lv0[1] and "x" not in lv0 and all(s["levels"] == lv0 for s in res["smoke"].values())
    ok = ok and all(v["max_rel_err"] < 1e-4 and not v["missing"] for v in rep.values())
    res["ok"] = bool(ok)
    # deliverables next to the netlists: GDS, picture, the LVS report
    shutil.copy(gds, os.path.join(DELIV, macro.CELL + ".gds"))
    png = os.path.join(RESULTS, macro.CELL + ".png")
    if os.path.exists(png):
        shutil.copy(png, os.path.join(DELIV, macro.CELL + ".png"))
    shutil.copy(lvs_out, os.path.join(DELIV, macro.CELL + ".lvs.out"))
    return res


def _wrong_w(sch):
    """The first device width of the schematic times 0.9 (the first line of subckt lvds_lane)."""
    import re
    m = re.search(r"^(X\S+ .* w=)([\d.]+)(u .*)$", sch, re.M)
    return sch.replace(m.group(0), f"{m.group(1)}{float(m.group(2)) * 0.9:g}{m.group(3)}", 1)


def _write(r, t0):
    run_lane.verdict(r)
    r["wall_s"] = round(time.time() - t0, 1)
    with open(os.path.join(RESULTS, r["cell"] + ".json"), "w") as f:
        json.dump(r, f, indent=1, default=str)
    import shutil
    g = os.path.join(OUT, r["cell"], r["cell"] + ".gds")
    if os.path.exists(g):
        shutil.copy(g, os.path.join(RESULTS, r["cell"] + ".gds"))
    print(r["cell"], r["verdict"], f"{r['wall_s']} s")
    for k, s in r["steps"].items():
        print("   %-16s %s %s" % (k, "ok" if s.get("ok") else "NOT OK", "" if s.get("ok") else str(s)[:1800]))
    return bool(r["all_ok"])


def pex_only():
    """--stage pex (T11): redo step 6 (PEX, repaired RC) on the GDS of the last full run, which must be the delivered one;
    the record of that run keeps its other steps, gains a note, and layout.json is rewritten from it."""
    import hashlib
    t0 = time.time()
    rec_p = os.path.join(RESULTS, macro.CELL + ".json")
    r = json.load(open(rec_p))
    wd = os.path.join(OUT, macro.CELL)
    gds = os.path.join(wd, macro.CELL + ".gds")
    sha = lambda p: hashlib.sha256(open(p, "rb").read()).hexdigest()
    if sha(gds) != sha(os.path.join(DELIV, macro.CELL + ".gds")):
        raise SystemExit("pex_only: the work GDS is not the delivered one; run the full flow")
    L, B = lane.build("route"), bias.build("route")
    M = macro.build(L, B)
    lvs_out = os.path.join(DELIV, macro.CELL + ".lvs.out")
    keep = os.path.join(wd, "lvs_out_delivered.txt")
    import shutil
    shutil.copy(lvs_out, keep)
    r["steps"]["pex"] = pex(L, B, M, wd, gds, keep)
    r.setdefault("notes", []).append("%s: step pex redone alone (--stage pex, T11: RC netlists repaired) on the same GDS" %
                                     time.strftime("%Y-%m-%d %H:%M:%S"))
    r["layout_json"] = layout_json(r, L, B, M)
    return _write(r, t0)


def main(args):
    nok = "--nok" in args
    stage = args[args.index("--stage") + 1] if "--stage" in args else "full"
    if stage == "pex":
        return 0 if pex_only() else 1
    return 0 if run(stage, nok) else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
