"""
worked_igs_gf180.py -- the book's Ex. 3.1 + Sec. 3.1.7 flow, run end to end on GF180 3.3 V (nfet_03v3):
  spec -> gm -> ID (3.8) -> W (3.9) with the self-loading iteration (3.10/3.11 idea) -> bias VGS by lookupVGS
  -> write an ngspice deck -> simulate -> compare gm/ID, gm/gds, ID, VGS and the unity-gain frequency with the LUT prediction.

Spec: intrinsic gain stage (Fig. 3.1): fu = 100 MHz into CL = 500 fF, gm/ID = 12, L = 0.5 um, VDS = 1.0 V.
The deck uses the book's trick (Fig. 3.5): a DC servo (huge-RC low-pass) sets VGS so that VDS = 1.0 V exactly
with an ideal drain current source, while the AC loop is open.  Finger count nf = max(round(W/2 um), 1)  (App. 3, C.3.1).

Run: docker exec apic_headless bash <...>/tools/cx python3 docs/book_extracts/worked_igs_gf180.py
Writes docs/book_extracts/worked_igs.spice and prints the comparison.
"""
import re
import subprocess
import numpy as np
from pygmid import Lookup

B = '/foss/designs/Analog/starter_files_open_source_tools/gf180mcuD/simulation/'
n = Lookup(B + 'nfet_03v3.mat')

fu, CL, gmid, L, VDS = 100e6, 500e-15, 12.0, 0.5, 1.0
jd = float(n.lookup('ID_W', GM_ID=gmid, L=L, VDS=VDS))            # A/um
cdd_w = float(n.lookup('CDD_W', GM_ID=gmid, L=L, VDS=VDS))        # F/um
ft = float(n.lookup('GM_CGG', GM_ID=gmid, L=L, VDS=VDS)) / 2 / np.pi
a0 = float(n.lookup('GM_GDS', GM_ID=gmid, L=L, VDS=VDS))
vgs = float(n.lookupVGS(GM_ID=gmid, L=L, VDS=VDS))
print('LUT at gm/ID=%g, L=%g um, VDS=%g V:  ID/W=%.4f uA/um  Cdd/W=%.3f fF/um  fT=%.2f GHz  gm/gds=%.1f  VGS=%.4f V' % (gmid, L, VDS, jd * 1e6, cdd_w * 1e15, ft / 1e9, a0, vgs))

print('\nself-loading iteration (book Sec. 3.1.7):')
Cdd = 0.0
for k in range(6):
    gm = 2 * np.pi * fu * (CL + Cdd)
    ID = gm / gmid
    W = ID / jd
    Cdd = W * cdd_w
    print('  iter %d: gm=%.4f mS  ID=%.3f uA  W=%.3f um  Cdd=%.2f fF' % (k + 1, gm * 1e3, ID * 1e6, W, Cdd * 1e15))
nf = max(int(round(W / 2.0)), 1)
FO = CL / (W * float(n.lookup('CGG_W', GM_ID=gmid, L=L, VDS=VDS)))
print('final: ID = %.3f uA, W = %.3f um (nf=%d, finger %.2f um), fan-out FO = CL/Cgg = %.0f (>10 OK), predicted |Av0| = %.1f' % (ID * 1e6, W, nf, W / nf, FO, a0))

deck = f"""* worked_igs.spice -- generated by worked_igs_gf180.py (book Ex. 3.1 / Sec. 3.1.7 on GF180)
.include /foss/pdks/gf180mcuD/libs.tech/ngspice/design.ngspice
.lib /foss/pdks/gf180mcuD/libs.tech/ngspice/sm141064.ngspice typical
vdd vdd 0 3.3
Ib vdd d dc {ID:.6e}
* drain-voltage servo: gate DC level = VGS0 + 1000*(Vd - VDS); the RC low-pass blocks the loop at AC (book Fig. 3.5)
Rlp d dlow 1G
Clp dlow 0 1
Eb vb 0 vol='{vgs:.6f} + 1000*(v(dlow) - {VDS})'
Vin g vb dc 0 ac 1
XM1 d g 0 0 nfet_03v3 L={L}u W={W:.5f}u nf={nf} ad='int((nf+1)/2) * W/nf * 0.18u' as='int((nf+2)/2) * W/nf * 0.18u' pd='2*int((nf+1)/2) * (W/nf + 0.18u)'
+ ps='2*int((nf+2)/2) * (W/nf + 0.18u)' nrd='0.18u / W' nrs='0.18u / W' sa=0 sb=0 sd=0 m=1
CL d 0 {CL:.4e}
.control
op
print @m.xm1.m0[id] @m.xm1.m0[gm] @m.xm1.m0[gds] v(g) v(d)
ac dec 40 1e3 5e9
meas ac av0 find vdb(d) at=1e4
meas ac fu when vdb(d)=0 fall=1
.endc
.end
"""
open('docs/book_extracts/worked_igs.spice', 'w').write(deck)
r = subprocess.run(['ngspice', '-b', 'docs/book_extracts/worked_igs.spice'], capture_output=True, text=True)
out = r.stdout + r.stderr


def grab(name):
    m = re.search(re.escape(name) + r'\s*=\s*([-+0-9.eE]+)', out)
    return float(m.group(1)) if m else float('nan')


idv, gmv, gdsv = grab('@m.xm1.m0[id]'), grab('@m.xm1.m0[gm]'), grab('@m.xm1.m0[gds]')
vg, vd = grab('v(g)'), grab('v(d)')
av0, fu_sim = grab('av0'), grab('fu')
print('\nngspice result vs prediction:')
print('  ID      sim %.3f uA   target %.3f uA   (%+.2f %%)' % (idv * 1e6, ID * 1e6, (idv / ID - 1) * 100))
print('  gm/ID   sim %.3f 1/V  target %.3f      (%+.2f %%)' % (gmv / idv, gmid, (gmv / idv / gmid - 1) * 100))
print('  gm/gds  sim %.1f       LUT    %.1f        (%+.1f %%)   [AC: |Av0| = %.2f dB = %.1f]' % (gmv / gdsv, a0, (gmv / gdsv / a0 - 1) * 100, av0, 10 ** (av0 / 20)))
print('  VGS     sim %.4f V    LUT lookupVGS %.4f V  (VDS sim %.4f V)' % (vg, vgs, vd))
print('  fu      sim %.2f MHz  target %.1f MHz   (%+.2f %%)' % (fu_sim / 1e6, fu / 1e6, (fu_sim / fu - 1) * 100))
