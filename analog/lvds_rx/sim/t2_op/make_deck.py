#!/usr/bin/env python3
"""make_deck.py -- write sim/t2_op/t2_op.spice (+ t2_op.json): the FIRST operating-point check of the sized netlist (task T2 part 1).

One lane of lvds_rx_x3 (lane 0 driven, lanes 1 and 2 held at VIC with VID = 0) at VIC / VID / EN from the grid; `op`, then one
`echo RESULT name value` line per node and per transistor of lane 0 and of the bias (id, gm, vgs, vds, saturation margin from the BSIM vdsat).
The device list is derived from netlist/lvds_circuit.py, so the deck cannot disagree with the netlist.
This is NOT the TB1 testbench of the plan (45 corners x 7 VIC x 3 VID); it is the first look that proves the netlist runs and every
device is in its intended region.   Re-generate:  python3 sim/t2_op/make_deck.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'netlist'))
import lvds_circuit as K  # noqa: E402

TOP = {'VDD': 'vdd', 'VSS': '0', 'RX0_P': 'rx0_p', 'RX0_N': 'rx0_n', 'RX1_P': 'rx1_p', 'RX1_N': 'rx1_n', 'RX2_P': 'rx2_p', 'RX2_N': 'rx2_n',
       'EN': 'en', 'RX0_O': 'rx0_o', 'RX1_O': 'rx1_o', 'RX2_O': 'rx2_o'}


def flatten(subckt, mapping, prefix, flags, out):
    """Collect (path, kind, stem, d, g, s, b) of every MOS with flattened ngspice net names."""
    for it in K.SUBCKTS[subckt][1]:
        if not K.cond_true(it[-1], flags):
            continue

        def mp(n):
            if n in mapping:
                return mapping[n]
            return (prefix + n.lower()) if n != '0' else '0'
        if it[0] == 'x':
            _, inst, nets, sname, _c = it
            ports = K.SUBCKTS[sname][0]
            flatten(sname, dict(zip(ports, [mp(n) for n in nets])), prefix + inst + '.', flags, out)
        elif it[0] in ('n', 'p'):
            _, inst, d, g, s, b, stem, _c = it
            out.append(dict(path=prefix + 'x' + inst, kind=it[0], inst=inst, stem=stem, d=mp(d), g=mp(g), s=mp(s), b=mp(b), prefix=prefix))


def main():
    flags = dict(nmos_pair=1, dump_devices=1)
    devs = []
    flatten('lvds_rx_x3', dict(TOP), 'xdut.', flags, devs)
    keep = [d for d in devs if d['prefix'] in ('xdut.xl0.xpre.', 'xdut.xl0.xhyst.', 'xdut.xl0.xout.', 'xdut.xbias.')]
    V = lambda n: '0' if n == '0' else 'v(%s)[n]' % n          # value at the LAST point of the supply ramp (n = index of the last point)
    lines = []
    keys = []
    for d in keep:
        k = d['path'].replace('xdut.', '').replace('.', '_').replace('x', '', 1) if False else d['path'].replace('xdut.', '').replace('.', '_')
        keys.append((k, d))
        lines.append('let vds_%s = abs(%s - %s)' % (k, V(d['d']), V(d['s'])))
        lines.append('let vgs_%s = abs(%s - %s)' % (k, V(d['g']), V(d['s'])))
        lines.append('let vsb_%s = abs(%s - %s)' % (k, V(d['s']), V(d['b'])))
        lines.append('let mg_%s = vds_%s - abs(@m.%s.m0[vdsat])' % (k, k, d['path']))
        lines.append('let id_%s = abs(@m.%s.m0[id])' % (k, d['path']))
        lines.append('let gm_%s = abs(@m.%s.m0[gm])' % (k, d['path']))
        for q in ('mg', 'id', 'gm', 'vgs', 'vds', 'vsb'):
            lines.append('echo RESULT %s_%s $&%s_%s' % (q, k, q, k))
    nodes = ['xdut.xl0.oa', 'xdut.xl0.ob', 'xdut.xl0.xpre.fa', 'xdut.xl0.xpre.fb', 'xdut.xl0.xpre.tp', 'xdut.xl0.xpre.tn',
             'xdut.xl0.d2a', 'xdut.xl0.d2b', 'xdut.xl0.xhyst.ts', 'xdut.xl0.xhyst.sa', 'xdut.xl0.xout.d3', 'xdut.xl0.xout.n3a',
             'xdut.xl0.xout.nd', 'xdut.xl0.xout.i1', 'xdut.xl0.xout.i2',
             'xdut.vbn', 'xdut.vbp', 'xdut.vb2', 'xdut.vref', 'xdut.xbias.vf', 'xdut.xbias.enb', 'xdut.xbias.nrb', 'rx0_o', 'rx1_o', 'rx2_o']
    # nets named 'xdut.vbn' etc. are the top-level internal nets (flattened as xdut.vbn)
    for n in nodes:
        lines.append('let vv = v(%s)[n]' % n)
        lines.append('echo RESULT v_%s $&vv' % n.replace('xdut.', '').replace('.', '_'))
    deck = """* t2_op: operating point of one lane of lvds_rx_x3 (task T2 part 1).  GENERATED by sim/t2_op/make_deck.py -- do not edit.
* grid: vic (common mode), vid (differential input, lane 0), en.  Lanes 1 and 2 sit at VIC with VID = 0.  Supply, EN and VIC are ramped together (dc sweep).
{header}
{seed_line}
* rshunt: a 100 Gohm resistor from every node to ground (7 nA in total at 3.6 V); without it EN = 0 leaves floating nodes and ngspice's gmin/source stepping fails
.option rshunt=1e11
.param vicv = {vic}
.param vidv = {vid}
.include {deck_dir}/../../sizing/sizes.spice
.include {deck_dir}/../../netlist/lvds_rx_core.spice
Vsup vdd 0 {vdd}
Ben en 0 V={en}*v(vdd)
Bcm cm 0 V={vic}*v(vdd)/{vdd}
Vp0 rx0_p cm dc {vidv/2}
Vn0 rx0_n cm dc {-vidv/2}
Vp1 rx1_p cm dc 0
Vn1 rx1_n cm dc 0
Vp2 rx2_p cm dc 0
Vn2 rx2_n cm dc 0
Xdut vdd 0 rx0_p rx0_n rx1_p rx1_n rx2_p rx2_n en rx0_o rx1_o rx2_o lvds_rx_x3
.control
* DC convergence: ramp the supply (and EN, VIC with it) from 0.3 V to VDD (a start at 0 V makes the first point fail), the last point is the operating point (plain `op` fails to converge on the
* regenerative stage 2: dynamic gmin, true gmin and source stepping all fail; the ramp finds the same state as a power-up transient, checked)
dc Vsup 0.3 {vdd} 0.1
let n = length(v(vdd)) - 1
let ivv = -i(Vsup)
let idd = ivv[n]
echo RESULT idd $&idd
""" + '\n'.join(lines) + """
.endc
.end
"""
    with open(os.path.join(HERE, 't2_op.spice'), 'w') as f:
        f.write(deck)
    spec = dict(name='t2_op', description='T2 part 1: first operating point of the sized lane (tt and worst5), VIC 0.05/1.2/2.35 V, VID +-100 mV, EN 0/1',
                deck='t2_op.spice', corners='worst5', grid=dict(vic=[0.05, 1.2, 2.35], vid=[-0.1, 0.1], en=[0, 1]), limits={}, timeout=120, jobs=6)
    with open(os.path.join(HERE, 't2_op.json'), 'w') as f:
        json.dump(spec, f, indent=1)
    json.dump([dict(key=k, path=d['path'], kind=d['kind'], stem=d['stem'], d=d['d'], g=d['g'], s=d['s'], b=d['b']) for k, d in keys],
              open(os.path.join(HERE, 'devices.json'), 'w'), indent=1)
    # ---- second deck: build flags (nmos_pair, dump_devices), outputs and node voltages only (the device list changes with the flags)
    fl = """* t2_flags: does the netlist run with the build flags switched?  GENERATED by sim/t2_op/make_deck.py -- do not edit.
{header}
{seed_line}
.option rshunt=1e11
.param vicv = {vic}
.param vidv = {vid}
.include {deck_dir}/../../sizing/sizes.spice
.param flag_nmos_pair = {nmos}
.param flag_dump_devices = {dump}
.include {deck_dir}/../../netlist/lvds_rx_core.spice
Vsup vdd 0 {vdd}
Ben en 0 V=1*v(vdd)
Bcm cm 0 V={vic}*v(vdd)/{vdd}
Vp0 rx0_p cm dc {vidv/2}
Vn0 rx0_n cm dc {-vidv/2}
Vp1 rx1_p cm dc 0
Vn1 rx1_n cm dc 0
Vp2 rx2_p cm dc 0
Vn2 rx2_n cm dc 0
Xdut vdd 0 rx0_p rx0_n rx1_p rx1_n rx2_p rx2_n en rx0_o rx1_o rx2_o lvds_rx_x3
.control
dc Vsup 0.3 {vdd} 0.1
let n = length(v(vdd)) - 1
let ivv = -i(Vsup)
let idd = ivv[n]
echo RESULT idd $&idd
let vv = v(rx0_o)[n]
echo RESULT v_rx0_o $&vv
let vv = v(xdut.xl0.oa)[n]
echo RESULT v_oa $&vv
let vv = v(xdut.xl0.ob)[n]
echo RESULT v_ob $&vv
let vv = v(xdut.xl0.d2a)[n]
echo RESULT v_d2a $&vv
let vv = v(xdut.xl0.d2b)[n]
echo RESULT v_d2b $&vv
.endc
.end
"""
    with open(os.path.join(HERE, 't2_flags.spice'), 'w') as f:
        f.write(fl)
    spec2 = dict(name='t2_flags', description='T2 part 1: build flags nmos_pair / dump_devices switched (tt): the netlist must run and the PMOS-only / no-dump variants behave as T1 predicted',
                 deck='t2_flags.spice', corners='tt', grid=dict(vic=[0.05, 0.6, 1.2, 1.8, 2.35], vid=[-0.1, 0.1], nmos=[0, 1], dump=[0, 1]), limits={}, timeout=120, jobs=6)
    with open(os.path.join(HERE, 't2_flags.json'), 'w') as f:
        json.dump(spec2, f, indent=1)
    # ---- third deck: stage-1 differential gain A1 and its -3 dB frequency at VID = 0 (ac after the supply ramp works: the ac op starts from the ramp state)
    ac = """* t2_ac: stage-1 gain (oa - ob) per unit differential input at VID = 0, and its -3 dB frequency.  GENERATED by sim/t2_op/make_deck.py -- do not edit.
{header}
{seed_line}
.option rshunt=1e11
.include {deck_dir}/../../sizing/sizes.spice
.include {deck_dir}/../../netlist/lvds_rx_core.spice
Vsup vdd 0 {vdd}
Ben en 0 V=1*v(vdd)
Bcm cm 0 V={vic}*v(vdd)/{vdd}
Vp0 rx0_p cm dc 0 ac 0.5
Vn0 rx0_n cm dc 0 ac -0.5
Vp1 rx1_p cm dc 0
Vn1 rx1_n cm dc 0
Vp2 rx2_p cm dc 0
Vn2 rx2_n cm dc 0
Xdut vdd 0 rx0_p rx0_n rx1_p rx1_n rx2_p rx2_n en rx0_o rx1_o rx2_o lvds_rx_x3
.control
dc Vsup 0.3 {vdd} 0.1
ac dec 20 1e6 3e9
let g = mag(v(xdut.xl0.ob) - v(xdut.xl0.oa))
let a1 = g[0]
let thr = a1 / 1.41421356
let n = length(g)
let fr = frequency
let k = 0
let f3 = 3e9
let found = 0
while k < n - 1
  if found = 0
    if g[k+1] < thr
      let f3 = fr[k] * exp(ln(fr[k+1] / fr[k]) * (g[k] - thr) / (g[k] - g[k+1]))
      let found = 1
    end
  end
  let k = k + 1
end
echo RESULT a1 $&a1
echo RESULT f3db $&f3
echo RESULT f3db_found $&found
.endc
.end
"""
    with open(os.path.join(HERE, 't2_ac.spice'), 'w') as f:
        f.write(ac)
    spec3 = dict(name='t2_ac', description='T2 part 1: stage-1 gain A1 and -3 dB frequency at VID = 0 (worst5, VIC 0.05/1.2/2.35 V)', deck='t2_ac.spice', corners='worst5',
                 grid=dict(vic=[0.05, 1.2, 2.35]), limits={}, timeout=120, jobs=6)
    with open(os.path.join(HERE, 't2_ac.json'), 'w') as f:
        json.dump(spec3, f, indent=1)
    print('wrote deck with %d devices' % len(keys))


if __name__ == '__main__':
    main()
