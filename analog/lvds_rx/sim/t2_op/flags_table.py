#!/usr/bin/env python3
"""flags_table.py -- summarise sim/t2_op/results/t2_flags: logic level of RX0_O per (nmos_pair, dump_devices, VIC) for VID = +-100 mV (tt).
Writes sim/t2_op/results/flags_table.md.  The default build (nmos_pair = 1, dump = 1) must be right at every VIC; the other builds are
the controls of PLAN_V2 4.2 (PMOS-only Option A: usable range stops near 1.6-2.1 V; no dump: stage-1 CM wanders)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
rs = json.load(open(os.path.join(HERE, 'results', 't2_flags', 'results.json')))['runs']
rows = {}
for r in rs:
    p = r['params']
    m = r['metrics'] or {}
    key = (p['nmos'], p['dump'], p['vic'])
    rows.setdefault(key, {})[p['vid']] = (r['status'], m.get('v_rx0_o', float('nan')), m.get('v_oa', float('nan')), m.get('v_ob', float('nan')))
out = ['# t2_flags: build flags (tt 27 C 3.3 V), RX0_O for VID = +100 mV (expect 3.3 V) and -100 mV (expect 0 V), generated by sim/t2_op/flags_table.py\n',
       '| nmos_pair | dump_devices | VIC (V) | RX0_O at +100 mV | RX0_O at -100 mV | stage-1 CM at +100 mV (V) | correct |',
       '|---|---|---|---|---|---|---|']
res = {}
for (nm, du, vic), v in sorted(rows.items()):
    hi, lo = v[0.1], v[-0.1]
    ok = hi[0] == 'ok' and lo[0] == 'ok' and hi[1] > 3.0 and lo[1] < 0.3
    res.setdefault((nm, du), []).append(ok)
    out.append('| %d | %d | %.2f | %.3f (%s) | %.3f (%s) | %.2f | %s |' % (nm, du, vic, hi[1], hi[0], lo[1], lo[0], 0.5 * (hi[2] + hi[3]), 'yes' if ok else 'NO'))
out.append('')
out.append('| nmos_pair | dump_devices | VIC points correct | of |')
out.append('|---|---|---|---|')
for k, v in sorted(res.items()):
    out.append('| %d | %d | %d | %d |' % (k[0], k[1], sum(v), len(v)))
open(os.path.join(HERE, 'results', 'flags_table.md'), 'w').write('\n'.join(out) + '\n')
print('\n'.join(out[-6:]))
