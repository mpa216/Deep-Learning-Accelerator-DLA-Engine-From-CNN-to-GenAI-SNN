#!/usr/bin/env python3
"""ac_table.py -- stage-1 gain A1 and -3 dB frequency from sim/t2_op/results/t2_ac against the sizing script's prediction
(PMOS path at VIC 0.05 V, NMOS path at VIC 2.35 V, f1 = 1/(2 pi RL Cout); corners with a table only).  Writes results/ac_table.md."""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'sizing'))
import lvds_rx_sizing as Z  # noqa: E402

S, devs = Z.design()
ev = Z.evaluate_corners(S, devs)
rs = json.load(open(os.path.join(HERE, 'results', 't2_ac', 'results.json')))['runs']
out = ['# t2_ac: stage-1 gain at VID = 0 and -3 dB frequency, SPICE vs sizing script (generated by sim/t2_op/ac_table.py)\n',
       '| corner | VIC (V) | A1 SPICE | A1 script | SPICE/script | f3dB SPICE (MHz) | f1 script (MHz) | status |', '|---|---|---|---|---|---|---|---|']
worst = 0.0
for r in sorted(rs, key=lambda r: (r['corner'], r['params']['vic'])):
    m = r['metrics'] or {}
    e = ev.get(r['corner'])
    vic = r['params']['vic']
    pred = None
    if e is not None and vic == 0.05:
        pred = e['s1']['a1p']
    elif e is not None and vic == 2.35:
        pred = e['s1']['a1n']
    a1 = m.get('a1', float('nan'))
    if pred:
        worst = max(worst, abs(a1 / pred - 1))
    out.append('| %s | %.2f | %.2f | %s | %s | %.0f | %s | %s |' % (r['corner'], vic, a1, '-' if pred is None else '%.2f' % pred, '-' if pred is None else '%.3f' % (a1 / pred),
                                                              m.get('f3db', float('nan')) / 1e6, '-' if e is None else '%.0f' % (e['s1']['f1'] / 1e6), r['status']))
out.append('\nlargest |SPICE/script - 1| at the extremes with a prediction: %.1f %%\n' % (worst * 100))
open(os.path.join(HERE, 'results', 'ac_table.md'), 'w').write('\n'.join(out) + '\n')
print('\n'.join(out))
