#!/usr/bin/env python3
"""check_op.py -- read the harness results of sim/t2_op and write sim/t2_op/results/op_table.md + results/t2_op.json.

For every run: status, logic level of the three outputs, supply current.  For the corner tt, VIC 1.2 V, EN = 1, VID = +100 mV and -100 mV:
a per-device table: ID, gm/ID, VGS from SPICE (BSIM .op) against the sizing script's LUT prediction at the SIMULATED bias
(VGS, VDS, VSB read from the op point) and against the script's design current; saturation margin VDS - vdsat from BSIM.
This is the LUT-vs-SPICE cross-check of PLAN_V2 C11 on the first netlist, restricted to tt / lane 0 / one VIC (TB1 does the full grid).

Usage (inside the container):  python3 sim/t2_op/check_op.py
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'sizing'))
sys.path.insert(0, os.path.join(ROOT, 'flow'))
import lvds_rx_sizing as Z  # noqa: E402
import common as C  # noqa: E402


def main():
    res = json.load(open(os.path.join(HERE, 'results', 't2_op', 'results.json')))['runs']
    devs = json.load(open(os.path.join(HERE, 'devices.json')))
    table = json.load(open(os.path.join(ROOT, 'layout', 'device_table.json')))
    by_stem = {d['stem']: d for d in table['devices']}
    out = []
    w = out.append
    w('# t2_op: first operating point of the sized lane (generated by sim/t2_op/check_op.py)\n')
    w('## Runs (all corners of worst5; VIC 0.05 / 1.2 / 2.35 V; EN 0/1; VID +-100 mV on lane 0, lanes 1 and 2 at VID = 0)\n')
    w('| corner | VIC (V) | EN | VID (mV) | status | RX0_O (V) | RX1_O | RX2_O | IDD total (uA) | verdict |')
    w('|---|---|---|---|---|---|---|---|---|---|')
    bad = 0
    summary = []
    for r in sorted(res, key=lambda r: (r['corner'], r['params']['vic'], r['params']['en'], r['params']['vid'])):
        m = r['metrics'] or {}
        vdd = r['vdd']
        o0 = m.get('v_rx0_o', float('nan'))
        exp = None
        if r['params']['en'] == 1:
            exp = vdd if r['params']['vid'] > 0 else 0.0
        else:
            exp = 0.0
        ok = r['status'] == 'ok' and abs(o0 - exp) < 0.1 * vdd and m.get('v_rx1_o', 0) in (m.get('v_rx1_o'),)
        if r['params']['en'] == 0:
            ok = ok and m.get('idd', 1) < 5e-6
        else:
            ok = ok and m.get('idd', 1) < 3 * Z.I_LANE_MAX + Z.I_BIAS_MAX
        bad += 0 if ok else 1
        w('| %s | %.2f | %d | %+.0f | %s | %.3f | %.3f | %.3f | %.3f | %s |' % (
            r['corner'], r['params']['vic'], r['params']['en'], r['params']['vid'] * 1e3, r['status'], o0, m.get('v_rx1_o', float('nan')), m.get('v_rx2_o', float('nan')),
            m.get('idd', float('nan')) * 1e6, 'PASS' if ok else 'FAIL'))
        summary.append(dict(corner=r['corner'], vic=r['params']['vic'], en=r['params']['en'], vid=r['params']['vid'], status=r['status'], rx0_o=o0, idd_uA=m.get('idd', float('nan')) * 1e6, ok=bool(ok)))
    w('')
    # ---- per-device table at tt, EN = 1, VID = +100 mV (output high) and the margins at -100 mV
    for vid in (0.1, -0.1):
        rr = [r for r in res if r['corner'] == 'tt_27c_3v30' and r['params']['en'] == 1 and abs(r['params']['vid'] - vid) < 1e-9 and abs(r['params']['vic'] - 1.2) < 1e-9]
        if not rr or rr[0]['status'] != 'ok':
            continue
        m = rr[0]['metrics']
        w('## Per-device operating point, tt 27 C 3.3 V, VIC 1.2 V, EN = 1, VID = %+.0f mV\n' % (vid * 1e3))
        w('Columns: ID design (script, tt) | ID SPICE | gm/ID SPICE | gm/ID LUT at the SPICE bias | VGS SPICE | VGS LUT at the SPICE ID and VDS | VDS (V) | VSB | margin VDS - vdsat (mV, BSIM) | note.\n')
        w('| device | ID design (uA) | ID SPICE (uA) | ID ratio | gm/ID SPICE | gm/ID LUT | VGS SPICE (V) | VGS LUT (V) | VDS (V) | VSB (V) | margin (mV) | region |')
        w('|---|---|---|---|---|---|---|---|---|---|---|---|')
        for d in devs:
            k = d['key']
            idv, gmv, vgs, vds, vsb, mg = (m['%s_%s' % (q, k)] for q in ('id', 'gm', 'vgs', 'vds', 'vsb', 'mg'))
            row = by_stem.get(d['stem'])
            dz = Z.D
            idd_design = (row or {}).get('ID_tt_uA')
            kind = d['kind']
            if row is None or idv < 1e-9:
                w('| %s | %s | %.3g | - | - | - | %.3f | - | %.3f | %.3f | %.0f | %s |' % (k, '-' if idd_design is None else '%.1f' % idd_design, idv * 1e6, vgs, vds, vsb, mg * 1e3, 'off' if idv < 1e-7 else ''))
                continue
            Wd, Ld = row['W_um'], row['L_um']
            jdv = idv / Wd
            try:
                gm_lut = Z.gmid_of_jd(kind, Z.TT, Ld, jdv, max(vds, 0.05), min(vsb, 2.0))
                vgs_lut = Z.vgs_of_jd(kind, Z.TT, Ld, jdv, max(vds, 0.05), min(vsb, 2.0))
            except Exception:
                gm_lut, vgs_lut = float('nan'), float('nan')
            region = 'sat' if mg > Z.VDSAT_MARGIN else ('MARGIN < 50 mV' if mg > 0 else 'TRIODE')
            ratio = (idv * 1e6 / idd_design) if idd_design else float('nan')
            w('| %s | %s | %.2f | %.2f | %.1f | %.1f | %.3f | %.3f | %.3f | %.3f | %.0f | %s |' % (
                k, '-' if idd_design is None else '%.1f' % idd_design, idv * 1e6, ratio, gmv / idv, gm_lut, vgs, vgs_lut, vds, vsb, mg * 1e3, region))
        w('')
    # ---- the in-saturation rule: every analog device that carries current must keep VDS - vdsat >= 50 mV (BSIM vdsat) in all runs with EN = 1
    analog = {'mbn', 'mbs', 'mbp', 'mb2p', 'mb2', 'mpt', 'mp1', 'mpd', 'mnt', 'mn1', 'mnd', 'm3', 'm5', 'mt2', 'ms', 'mld', 'mlc'}
    w('## Saturation margin of the analog devices (min over the devices carrying > 1 uA; BSIM vdsat), all corners of worst5, EN = 1\n')
    w('Switches (msw, mvs, men_*, mpu_*, mpd_*), the digital chain and the stage-3 mirror (rail-to-rail by design) are excluded: they are meant to be in triode / off.\n')
    w('| corner | VIC (V) | VID (mV) | min margin (mV) | at device | limit 50 mV |')
    w('|---|---|---|---|---|---|')
    sat_fail = 0
    worst = {}
    for r in sorted(res, key=lambda r: (r['corner'], r['params']['vic'], r['params']['vid'])):
        if r['params']['en'] != 1 or r['status'] != 'ok':
            continue
        m = r['metrics']
        best = None
        for d in devs:
            if d['stem'] not in analog or m['id_%s' % d['key']] < 1e-6:
                continue
            mg = m['mg_%s' % d['key']]
            if best is None or mg < best[0]:
                best = (mg, d['key'])
        okk = best is not None and best[0] >= Z.VDSAT_MARGIN
        sat_fail += 0 if okk else 1
        worst[(r['corner'], r['params']['vic'], r['params']['vid'])] = best
        w('| %s | %.2f | %+.0f | %.0f | %s | %s |' % (r['corner'], r['params']['vic'], r['params']['vid'] * 1e3, best[0] * 1e3, best[1], 'PASS' if okk else 'FAIL'))
    w('')
    bad += sat_fail
    path = os.path.join(HERE, 'results', 'op_table.md')
    open(path, 'w').write('\n'.join(out) + '\n')
    C.write_json(os.path.join(ROOT, 'results', 't2_op.json'), dict(runs=summary, failed=bad))
    print('wrote', os.path.relpath(path, ROOT), '; run verdicts failed:', bad)
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main())
