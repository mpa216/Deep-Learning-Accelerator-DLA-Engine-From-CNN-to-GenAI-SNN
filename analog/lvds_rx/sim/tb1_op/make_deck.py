#!/usr/bin/env python3
"""make_deck.py -- write the TB1 decks and specs (task T2 part 2).  The device list comes from netlist/lvds_circuit.py, so the decks cannot
disagree with the netlist.   Re-generate after any change of the circuit:   python3 sim/tb1_op/make_deck.py

  tb1_op.spice / tb1_op.json   operating point of lane 0 (+ bias) at VIC x VID, EN = 1; one `echo RESULT` per device quantity and node
  tb1_np.spice / tb1_np.json   dump-free control (flag_dump_devices = 0): tail currents of both pairs vs VIC at VID = 0 -> N/P overlap (decision D-002)
  devices.json                 key, stem, kind, nets of every device printed
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'sim', 't2_op'))
import make_deck as T2  # noqa: E402  (flatten, TOP)

VICS = [0.05, 0.3, 0.6, 1.2, 1.8, 2.1, 2.35]
VIDS = [-0.1, 0.0, 0.1]
NP_VICS = [round(0.05 * k, 2) for k in range(1, 48)]       # 0.05 .. 2.35 V in 50 mV steps (47 points, as the T1 spike)

HDR = """{header}
{seed_line}
* rshunt: 100 Gohm from every node to ground (7 nA at 3.6 V): without it floating nodes break ngspice's gmin/source stepping
.option rshunt=1e11
"""
SRC = """Vsup vdd 0 {vdd}
Ben en 0 V=1*v(vdd)
Bcm cm 0 V={vic}*v(vdd)/{vdd}
Vp0 rx0_p cm dc {vidv/2}
Vn0 rx0_n cm dc {-vidv/2}
Vp1 rx1_p cm dc 0
Vn1 rx1_n cm dc 0
Vp2 rx2_p cm dc 0
Vn2 rx2_n cm dc 0
Xdut vdd 0 rx0_p rx0_n rx1_p rx1_n rx2_p rx2_n en rx0_o rx1_o rx2_o lvds_rx_x3
"""


def main():
    flags = dict(nmos_pair=1, dump_devices=1)
    devs = []
    T2.flatten('lvds_rx_x3', dict(T2.TOP), 'xdut.', flags, devs)
    keep = [d for d in devs if d['prefix'] in ('xdut.xl0.xpre.', 'xdut.xl0.xhyst.', 'xdut.xl0.xout.', 'xdut.xbias.')]
    V = lambda n: '0' if n == '0' else 'v(%s)[n]' % n
    lines, keys, nets = [], [], []
    for d in keep:
        k = d['path'].replace('xdut.', '').replace('.', '_')
        keys.append((k, d))
        for n in (d['d'], d['g'], d['s'], d['b']):
            if n not in nets and n != '0':
                nets.append(n)
        lines.append('let vds_%s = abs(%s - %s)' % (k, V(d['d']), V(d['s'])))
        lines.append('let vgs_%s = abs(%s - %s)' % (k, V(d['g']), V(d['s'])))
        lines.append('let vsb_%s = abs(%s - %s)' % (k, V(d['s']), V(d['b'])))
        lines.append('let mg_%s = vds_%s - abs(@m.%s.m0[vdsat])' % (k, k, d['path']))
        lines.append('let id_%s = abs(@m.%s.m0[id])' % (k, d['path']))
        lines.append('let gm_%s = abs(@m.%s.m0[gm])' % (k, d['path']))
        for q in ('mg', 'id', 'gm', 'vgs', 'vds', 'vsb'):
            lines.append('echo RESULT %s_%s $&%s_%s' % (q, k, q, k))
    for n in nets:
        lines.append('let vv = v(%s)[n]' % n)
        lines.append('echo RESULT v_%s $&vv' % n.replace('xdut.', '').replace('.', '_'))
    deck = ("* tb1_op: operating point of lane 0 + bias of lvds_rx_x3 (task T2 part 2, PLAN_V2 TB1).  GENERATED by sim/tb1_op/make_deck.py -- do not edit.\n"
            "* grid: vic (common mode), vid (differential input of lane 0).  EN = 1.  Lanes 1 and 2 sit at VIC with VID = 0.\n"
            "* Hooks (hooks.py:post_tb1) compare every device with the sizing script / LUT and write the pass/fail metrics.\n"
            + HDR +
            ".param vidv = {vid}\n.include {deck_dir}/../../sizing/sizes.spice\n.include {deck_dir}/../../netlist/lvds_rx_core.spice\n" + SRC +
            ".control\n"
            "* DC convergence: ramp the supply (EN and VIC scale with it) from 0.3 V to VDD; the last point is the operating point (plain `op` fails, see log/T2_report.md)\n"
            "dc Vsup 0.3 {vdd} 0.1\n"
            "let n = length(v(vdd)) - 1\n"
            "let ivv = -i(Vsup)\nlet idd = ivv[n]\necho RESULT idd $&idd\n" + '\n'.join(lines) + "\n.endc\n.end\n")
    open(os.path.join(HERE, 'tb1_op.spice'), 'w').write(deck)
    json.dump([dict(key=k, path=d['path'], kind=d['kind'], stem=d['stem'], d=d['d'], g=d['g'], s=d['s'], b=d['b']) for k, d in keys],
              open(os.path.join(HERE, 'devices.json'), 'w'), indent=1)
    spec = dict(name='tb1_op', description='TB1: operating point, headroom, LUT-vs-SPICE, stage-1 CM, currents, node range (lane 0 + bias; EN = 1)',
                deck='tb1_op.spice', corners='full47', grid=dict(vic=VICS, vid=VIDS), post='hooks.py:post_tb1',
                limits={'min_headroom_v': {'min': 0.05, 'scale': 1000, 'unit': 'mV'}, 'gmid_err': {'min': -0.10, 'max': 0.10},
                        'id_err': {'min': -0.10, 'max': 0.10}, 'vgs_err_v': {'min': -0.03, 'max': 0.03, 'scale': 1000, 'unit': 'mV'},
                        's1_cm_dev_v': {'min': -0.15, 'max': 0.15, 'scale': 1000, 'unit': 'mV'}, 'np_overlap_v': {'min': 0.25},
                        'vnode_min_v': {'min': -0.3}, 'vnode_over_vdd_v': {'max': 0.3}, 'model_warnings': {'max': 0}},
                timeout=120, jobs=6)
    json.dump(spec, open(os.path.join(HERE, 'tb1_op.json'), 'w'), indent=1)
    # ---- dump-free control for the N/P overlap (D-002): same sizes, dump gates disconnected, VID = 0
    npd = ("* tb1_np: dump-free control of the stage-1 input (flag_dump_devices = 0): tail currents of the PMOS and NMOS pair vs VIC at VID = 0.  GENERATED -- do not edit.\n"
           "* np_overlap_v (decision D-002) = width of the VIC window in which BOTH tails carry >= 90 % of their plateau current, limited to 2 x the distance of Vref\n"
           "* from either window edge (Vref must lie >= 0.125 V inside the window); evaluated by hooks.py:np_overlap from these runs.\n"
           + HDR +
           ".include {deck_dir}/../../sizing/sizes.spice\n.param flag_dump_devices = 0\n.include {deck_dir}/../../netlist/lvds_rx_core.spice\n"
           + SRC.replace('{vidv/2}', '0').replace('{-vidv/2}', '0') +
           ".control\ndc Vsup 0.3 {vdd} 0.1\nlet n = length(v(vdd)) - 1\n"
           "let x = abs(@m.xdut.xl0.xpre.xmpt.m0[id])\necho RESULT id_mpt $&x\n"
           "let x = abs(@m.xdut.xl0.xpre.xmnt.m0[id])\necho RESULT id_mnt $&x\n"
           "let x = v(xdut.vref)[n]\necho RESULT v_vref $&x\n"
           "let x = v(xdut.xl0.oa)[n]\necho RESULT v_oa $&x\n"
           ".endc\n.end\n")
    open(os.path.join(HERE, 'tb1_np.spice'), 'w').write(npd)
    json.dump(dict(name='tb1_np', description='TB1 helper: dump-free control for the N/P overlap (decision D-002); VID = 0, EN = 1, 47 VIC points',
                   deck='tb1_np.spice', corners='full47', grid=dict(vic=NP_VICS), vars=dict(vid=0.0), limits={}, timeout=120, jobs=6),
              open(os.path.join(HERE, 'tb1_np.json'), 'w'), indent=1)
    print('wrote TB1 decks with %d devices, %d nodes' % (len(keys), len(nets)))


if __name__ == '__main__':
    main()
