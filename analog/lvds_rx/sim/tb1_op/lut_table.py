#!/usr/bin/env python3
"""lut_table.py -- the LUT-vs-SPICE table of TB1 (PLAN_V2 5.2 item 3) -> sim/tb1_op/results/lut_vs_spice.md (+ stdout summary).

Reads the per-run lutcmp.json files (written by hooks.py) of sim/tb1_op/results/tb1_op/work and the metrics of results.json.
Section 1: gate metrics per corner (worst over VIC x VID) against the limits.  Section 2: per device and corner, the worst gm/ID, VGS, ID error and the smallest
VDS - vdsat margin over the 21 (VIC, VID) points.  Section 3: tt, VIC = 1.2 V, VID = +100 mV, the whole device table.

Usage (container):  python3 sim/tb1_op/lut_table.py
"""
import glob
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'flow'))
import common as C  # noqa: E402


def main():
    spec = C.load_yaml('spec/spec.yaml')
    lim = spec['tb1']
    res = json.load(open(os.path.join(HERE, 'results', 'tb1_op', 'results.json')))['runs']
    wd = os.path.join(HERE, 'results', 'tb1_op', 'work')
    out = []
    w = out.append
    nbad = sum(1 for r in res if r['status'] != 'ok')
    w('# TB1: operating point and LUT-vs-SPICE table (generated by sim/tb1_op/lut_table.py)\n')
    w('%d runs (%d not ok). Limits: headroom >= %.0f mV, |gm/ID err| <= %.0f %%, |ID err| <= %.0f %%, |VGS err| <= %.0f mV, stage-1 CM span/2 <= %.0f mV, '
      'N/P overlap >= %.2f V.\n' % (len(res), nbad, lim['vdsat_headroom_min_v'] * 1e3, lim['gmid_rel_tol'] * 100, lim['id_rel_tol'] * 100, lim['vgs_abs_tol_v'] * 1e3,
                                    spec['stage1']['out_cm_window_v'] * 1e3, spec['stage1']['np_overlap_min_v']))
    w('Reference for gm/ID and VGS = the gm/ID look-up table of the corner (tt, ss/125 C, ff/-40 C; fs, sf and any other corner use the tt table = proxy) read at the '
      'SIMULATED ID/W, VDS and VSB; reference for ID = the sizing script\'s corner solution (fixed-current devices only: reference, tails, sinks, stage-2 tail).\n')
    # ---- 1 per corner
    w('## 1. Gate metrics per corner (worst over the VIC x VID points)\n')
    w('| corner | LUT table | min headroom (mV) | gm/ID err (%) | ID err (%) | VGS err (mV) | stage-1 CM span (mV) | N/P overlap (V) / Vref margin (V) | node min (V) | node - VDD (V) | I_bias (uA) | I_lane (uA) | warnings |')
    w('|---|---|---|---|---|---|---|---|---|---|---|---|---|')
    by = {}
    for r in res:
        by.setdefault(r['corner'], []).append(r)
    for c, rs in by.items():
        ok = [r for r in rs if r['status'] == 'ok']
        if not ok:
            w('| %s | all runs failed |' % c)
            continue
        M = lambda k: [r['metrics'][k] for r in ok]
        absmax = lambda k: max(M(k), key=abs)
        lt = json.load(open(os.path.join(wd, os.path.basename(ok[0]['run_dir'].rstrip('/')), 'lutcmp.json')))['lut_table']
        w('| %s | %s | %.0f | %+.1f | %+.1f | %+.1f | %.0f | %.2f / %.3f | %.3f | %+.3f | %.0f | %.0f | %d |' % (
            c, lt, min(M('min_headroom_v')) * 1e3, absmax('gmid_err') * 100, absmax('id_err') * 100, absmax('vgs_err_v') * 1e3,
            max(M('s1_cm_span_v')) * 1e3, M('np_overlap_v')[0], M('np_vref_margin_v')[0], min(M('vnode_min_v')), max(M('vnode_over_vdd_v')),
            max(M('i_bias_a')) * 1e6, max(M('i_lane_a')) * 1e6, sum(M('model_warnings'))))
    w('')
    # ---- 2 per device and corner
    devs = {}
    for c in by:
        for r in by[c]:
            if r['status'] != 'ok':
                continue
            j = json.load(open(os.path.join(wd, os.path.basename(r['run_dir'].rstrip('/')), 'lutcmp.json')))
            for k, d in j['devices'].items():
                if d.get('off') or d.get('triode'):
                    continue
                e = devs.setdefault(d['stem'], {}).setdefault(c, dict(n=0, g=0.0, v=0.0, i=None, mg=1e9, mgat=''))
                e['n'] += 1
                e['g'] = max(e['g'], abs(d['gmid_err']))
                e['v'] = max(e['v'], abs(d['vgs_err']))
                if 'id_err' in d:
                    e['i'] = max(abs(d['id_err']), e['i'] or 0.0)
                if d['mg'] < e['mg']:
                    e['mg'], e['mgat'] = d['mg'], '%.2f/%+.0f' % (j['vic'], j['vid'] * 1e3)
    w('## 2. Per device and corner: worst |gm/ID err| %, |VGS err| mV, |ID err| % (fixed-current devices), smallest VDS - vdsat (mV at VIC/VID mV); runs with ID < 1 uA are skipped\n')
    cs = list(by)
    w('| device | ' + ' | '.join(cs) + ' |')
    w('|---|' + '---|' * len(cs))
    for stem in sorted(devs):
        cells = []
        for c in cs:
            e = devs[stem].get(c)
            cells.append('-' if not e else '%.1f %% / %.0f mV / %s / %.0f mV (%s) [%d]' % (e['g'] * 100, e['v'] * 1e3, '-' if e['i'] is None else '%.1f %%' % (e['i'] * 100), e['mg'] * 1e3, e['mgat'], e['n']))
        w('| %s | ' % stem + ' | '.join(cells) + ' |')
    w('')
    # ---- 3 tt detail
    w('## 3. tt 27 C 3.3 V, VIC = 1.2 V, VID = +100 mV: every analog device (SPICE vs table / script)\n')
    w('| device | ID SPICE (uA) | ID script (uA) | gm/ID SPICE | gm/ID LUT | VGS SPICE (V) | VGS LUT (V) | VDS (V) | VSB (V) | VDS - vdsat (mV) |')
    w('|---|---|---|---|---|---|---|---|---|---|')
    for r in by.get('tt_27c_3v30', []):
        if r['status'] == 'ok' and abs(r['params']['vic'] - 1.2) < 1e-9 and abs(r['params']['vid'] - 0.1) < 1e-9:
            j = json.load(open(os.path.join(wd, os.path.basename(r['run_dir'].rstrip('/')), 'lutcmp.json')))
            for k, d in sorted(j['devices'].items()):
                if d.get('off') or d.get('triode'):
                    w('| %s | %.2g (off) | | | | | | | | |' % (k, d['id'] * 1e6))
                else:
                    w('| %s | %.2f | %s | %.1f | %.1f | %.3f | %.3f | %.3f | %.3f | %.0f |' % (
                        k, d['id'] * 1e6, '-' if 'id_script' not in d else '%.2f' % (d['id_script'] * 1e6), d['gmid'], d['gmid_lut'], d['vgs'], d['vgs_lut'], d['vds'], d['vsb'], d['mg'] * 1e3))
    p = os.path.join(HERE, 'results', 'lut_vs_spice.md')
    open(p, 'w').write('\n'.join(out) + '\n')
    print('\n'.join(out[:14]))
    print('wrote', os.path.relpath(p, ROOT))
    return 0


if __name__ == '__main__':
    sys.exit(main())
