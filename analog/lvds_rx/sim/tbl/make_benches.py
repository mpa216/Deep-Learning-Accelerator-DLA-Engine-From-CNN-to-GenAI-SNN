#!/usr/bin/env python3
"""make_benches.py -- the post-layout benches of gate TBL (task T11, PLAN_V2 6.5).

  python3 sim/tbl/make_benches.py      writes sim/tbl_<name>/tbl_<name>.spice + tbl_<name>_pre.json + tbl_<name>_pex.json

Every bench is the pre-layout bench with ONE circuit change: the line `.include {deck_dir}/../../netlist/lvds_rx_core.spice`
becomes `.include {deck_dir}/../../{core}`; the _pre spec sets core = netlist/lvds_rx_core.spice, the _pex spec
core = sim/tbl/core_pexrc.spice (sim/tbl/make_cores.py: the extracted macro, RC on all nets, its nodes named after the
pre-layout paths).  Both specs share deck, corners and grid, so the evaluator compares each extracted run with the
pre-layout run of the same deck, corner and grid point.  Hooks and limits are the pre-layout bench's own.
One output change: a `.save` line before `.control` lists the vectors the control section reads (its v(...) and i(...)),
because ngspice keeps every node of a transient in memory and the RC netlist has about 9400 nodes (TB4 at 18000 time
points asked for 548 MB and was refused).  Saving fewer vectors does not change the solution.
TB2 scales the two cross-coupled loads of lane 0 with `alter` (pre-layout: two devices); in the extracted netlist they are
ten fingers (sim/tbl/mlc.json), so the two `alter` lines become the placeholder {alters}.
TB1 probes every device (LUT and headroom metrics); a flat extracted netlist has no schematic devices and one VDD net for
the three lanes and the bias block, so tbl_op is a compact new bench: total supply current, stage-1 output common mode,
the node voltages and the model-warning count of TB1, at the 7 VIC of TB1 (the evaluator forms s1_cm_dev_v over them
as TB1 does) and VID = +-100 mV (VID = 0 leaves the latch state open), at tt and at the D-012 corner.
Corners: the 6.5 list plus the least-margin corners of the pre-layout full tier (log/T11_notes.md); tbl_eye is the eye
run that the D-012 freeze condition asks for (ff/125C/3.6 V, VIC 0.05 V; eye15 of TB5 has no such corner).
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SIM = os.path.dirname(HERE)
INC = ".include {deck_dir}/../../netlist/lvds_rx_core.spice"
CORES = {"pre": "netlist/lvds_rx_core.spice", "pex": "sim/tbl/core_pexrc.spice"}
D012 = "ff:125:3.6"                                      # AUDIT_1 D-012: re-check fast-hot-3.6 V after extraction

BENCHES = {
    # name: (source dir, source spec, corners, grid, timeout factor for the extracted runs)
    "tbl_ac":    ("tb2_ac", "tb2_ac", ["worst5", D012], {"vic": [0.05, 1.2, 2.35]}, 10),
    "tbl_trip":  ("tb3_trip", "tb3_trip", ["worst5", "sf:-40:3.0"], {"vic": [0.05, 1.2, 2.35], "sweep": [0, 1]}, 10),
    "tbl_pd":    ("tb4_pd", "tb4_pd", ["worst5", D012], {"vic": [0.05, 1.2, 2.35], "vid": [0.1, 0.35]}, 10),
    "tbl_pkg":   ("tb12_pkg", "tb12_pkg", ["ss:125:3.0", "fs:27:3.3"], {"pkg": [0, 1, 2, 3], "rate": [1e8, 2e8]}, 10),
    "tbl_eye":   ("tb5_eye", "tb5_eye", [D012], {"vic": [0.05], "vid": [0.1, 0.35], "rate": [1e8, 2e8]}, 10),   # D-012 eye run
    "tbl_idle":  ("tb7_idle", "tb7_idle", "worst5", {"vic": [1.2], "term": [0, 1, 2]}, 10),
    "tbl_en":    ("tb8_en", "tb8_en", [D012, "ss:125:3.0", "tt:27:3.3"], {"case": [0, 1, 2, 3, 4, 5, 6, 7]}, 10),   # 6, 7: D-019
    "tbl_lanes": ("tb10_lanes", "tb10_lanes", "tt", {"mc3s": [0]}, 10),
}

OP_PROBES = ["vbn", "vbp", "vb2", "vref", "xbias.enb", "xbias.nrb", "xbias.vf", "xbias.nmid", "xl0.xpre.tp", "xl0.xpre.tn",
             "xl0.xpre.fa", "xl0.xpre.fb", "xl0.oa", "xl0.ob", "xl0.xhyst.ts", "xl0.xhyst.sa", "xl0.xhyst.sb", "xl0.d2a", "xl0.d2b",
             "xl0.xout.n3a", "xl0.xout.d3", "xl0.xout.nd", "xl0.xout.i1", "xl0.xout.i2", "xl1.oa", "xl1.ob", "xl2.oa", "xl2.ob"]


def op_deck():
    """tbl_op: operating point by a supply ramp (the TB2 method: plain `op` does not converge on this netlist)."""
    lines = ["* tbl_op: post-layout operating point (task T11, gate TBL; the measurable part of TB1).  GENERATED by sim/tbl/make_benches.py.",
             "* Lane 0 at VIC +- VID/2, lanes 1 and 2 at VIC with VID / 2 the other way.  RESULT: idd_a, s1_cm_v, v_<node>.",
             "{header}", "{seed_line}", ".option rshunt=1e11",
             ".include {deck_dir}/../../sizing/sizes.spice", ".include {deck_dir}/../../{core}",
             "Vr r 0 {vdd}", "Bv vddi 0 V=v(r)", "Vs vdd vddi dc 0", "Ben en 0 V=1*v(r)", "Bcm cm 0 V={vic}*v(r)/{vdd}",
             "Vp0 rx0_p cm dc {0.5*({vid})}", "Vn0 rx0_n cm dc {-0.5*({vid})}", "Vp1 rx1_p cm dc {-0.5*({vid})}",
             "Vn1 rx1_n cm dc {0.5*({vid})}", "Vp2 rx2_p cm dc {0.5*({vid})}", "Vn2 rx2_n cm dc {-0.5*({vid})}",
             "Xdut vdd 0 rx0_p rx0_n rx1_p rx1_n rx2_p rx2_n en rx0_o rx1_o rx2_o lvds_rx_x3",
             ".control", "dc Vr 0.3 {vdd} 0.1", "let n = length(v(vdd)) - 1",
             "let x = -i(Vs)[n]", "echo RESULT idd_a $&x",
             "let x = (v(xdut.xl0.oa)[n] + v(xdut.xl0.ob)[n]) / 2", "echo RESULT s1_cm_v $&x"]
    for p in OP_PROBES:
        lines += [f"let x = v(xdut.{p})[n]", f"echo RESULT v_{p.replace('.', '_')} $&x"]
    for k in range(3):
        lines += [f"let x = v(rx{k}_o)[n]", f"echo RESULT out{k}_v $&x"]
    lines += [".endc", ".end"]
    return "\n".join(lines) + "\n"


OP_HOOKS = '''"""hooks.py (tbl_op): node range from the RESULT v_* metrics (gate TB1: vnode_min_v >= -0.3, vnode_over_vdd_v <= 0.3)
and model_warnings counted as sim/tb1_op/hooks.py counts them.  GENERATED by sim/tbl/make_benches.py."""
import os


def post(ctx):
    v = [float(x) for k, x in ctx["measures"].items() if k.startswith("v_")]
    n = 0
    try:
        for ln in open(os.path.join(ctx["run_dir"], "ngspice.log"), errors="replace"):
            low = ln.lower()
            if "warning" in low and "comments and warnings go to log-file" not in low and "stepping failed" not in low:
                n += 1
    except OSError:
        n = float("nan")
    return {"vnode_min_v": min(v), "vnode_over_vdd_v": max(v) - float(ctx["corner"].vdd), "model_warnings": float(n)}
'''


def save_line(deck):
    """`.save` of every v(...) / i(...) the control section reads, in order of first use."""
    m = re.search(r"^\.control\s*$(.*?)^\.endc", deck, re.M | re.S)
    if not m:
        raise SystemExit("no .control section")
    vecs, seen = [], set()
    for v in re.finditer(r"\b([vViI])\(([^()\s]+)\)", m.group(1)):
        s = f"{v.group(1).lower()}({v.group(2)})"
        if s.lower() not in seen:
            seen.add(s.lower())
            vecs.append(s)
    if not vecs:
        raise SystemExit("the control section reads no vector")
    return ".save " + " ".join(vecs)


def main():
    mlc = json.load(open(os.path.join(HERE, "mlc.json")))
    alters_pre = "alter m.xdut.xl0.xhyst.xmlc1.m0 m = 0.001\nalter m.xdut.xl0.xhyst.xmlc2.m0 m = 0.001"
    alters_pex = "\n".join(f"alter m.xdut.{x}.m0 m = 0.001" for x in mlc["pexrc"]["mlc_fingers"])
    made = []
    for name, (src, sname, corners, grid, tf) in BENCHES.items():
        spec = json.load(open(os.path.join(SIM, src, sname + ".json")))
        deck = open(os.path.join(SIM, src, spec["deck"])).read()
        if deck.count(INC) != 1:
            raise SystemExit(f"{name}: the core include is not exactly once in {src}/{spec['deck']}")
        deck = deck.replace(INC, ".include {deck_dir}/../../{core}")
        if name == "tbl_ac":
            deck = deck.replace(alters_pre, "{alters}")
            if "{alters}" not in deck:
                raise SystemExit("tbl_ac: the two alter lines were not found")
        if len(re.findall(r"^\.control\s*$", deck, re.M)) != 1:
            raise SystemExit(f"{name}: not exactly one .control line")
        deck = re.sub(r"^\.control\s*$", lambda _m: save_line(deck) + "\n.control", deck, count=1, flags=re.M)
        hdr = (f"* {name}: post-layout variant of sim/{src}/{spec['deck']} (T11, gate TBL), GENERATED by sim/tbl/make_benches.py:"
               " the core include is a variable and a .save line keeps only the vectors the control section reads.\n")
        d = os.path.join(SIM, name)
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, name + ".spice"), "w") as f:
            f.write(hdr + deck)
        for var in ("pre", "pex"):
            s = {k: v for k, v in spec.items() if k not in ("name", "deck", "corners", "grid", "vars", "prep", "post", "timeout", "jobs", "retry")}
            s.update(name=f"{name}_{var}", deck=name + ".spice", corners=corners, grid=grid, jobs=4,
                     vars=dict(spec.get("vars", {}), core=CORES[var]),
                     timeout=int(spec.get("timeout", 300) * (tf if var == "pex" else 1)))
            if name == "tbl_ac":
                s["vars"]["alters"] = alters_pre if var == "pre" else alters_pex
            for h in ("prep", "post"):
                if spec.get(h):
                    s[h] = spec[h] if spec[h].startswith("../") else f"../{src}/{spec[h]}"
            if spec.get("retry"):
                s["retry"] = dict(spec["retry"], timeout=int(spec["retry"].get("timeout", 300) * (tf if var == "pex" else 1)))
            s["description"] = f"post-layout gate TBL ({var}): {src} with core = {CORES[var]}"
            with open(os.path.join(d, f"{name}_{var}.json"), "w") as f:
                json.dump(s, f, indent=1)
        made.append(name)
    # tbl_op: the new operating-point bench
    d = os.path.join(SIM, "tbl_op")
    os.makedirs(d, exist_ok=True)
    with open(os.path.join(d, "tbl_op.spice"), "w") as f:
        f.write(op_deck())
    with open(os.path.join(d, "hooks.py"), "w") as f:
        f.write(OP_HOOKS)
    for var in ("pre", "pex"):
        s = dict(name=f"tbl_op_{var}", deck="tbl_op.spice", corners=["tt", D012],
                 grid={"vic": [0.05, 0.3, 0.6, 1.2, 1.8, 2.1, 2.35], "vid": [-0.1, 0.1]},
                 vars=dict(core=CORES[var]), post="hooks.py:post", timeout=600 if var == "pex" else 120, jobs=4,
                 limits={"vnode_min_v": {"min": -0.3}, "vnode_over_vdd_v": {"max": 0.3}},
                 description=f"post-layout gate TBL ({var}): operating point, core = {CORES[var]}")
        with open(os.path.join(d, f"tbl_op_{var}.json"), "w") as f:
            json.dump(s, f, indent=1)
    made.append("tbl_op")
    print("benches:", made)


if __name__ == "__main__":
    main()
