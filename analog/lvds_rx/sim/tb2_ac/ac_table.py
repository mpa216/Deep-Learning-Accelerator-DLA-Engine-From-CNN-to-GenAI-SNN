#!/usr/bin/env python3
"""ac_table.py -- compact table of the TB2 results (per corner: min / max over VIC) -> sim/tb2_ac/results/ac_table.md.

Usage (container):  python3 sim/tb2_ac/ac_table.py [results.json]
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'flow'))
import common as C  # noqa: E402


def main():
    path = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'results', 'tb2_ac', 'results.json')
    runs = json.load(open(path))['runs']
    bad = [r for r in runs if r['status'] != 'ok']
    spec = C.load_yaml('spec/spec.yaml')
    out = ['# TB2 (generated by sim/tb2_ac/ac_table.py): %d runs, %d not ok\n' % (len(runs), len(bad)),
           'A1 = stage-1 differential gain; f1/f2/f3 = -3 dB frequency of stage 1 (oa-ob per input), stage 2 (d2 diff per oa-ob, hysteresis feedback scaled to 0), '
           'stage 3 (d3 per d2 diff); chain = d3 per input. CMRR/PSRR half-circuit at 1 MHz. Per corner: min .. max over the 7 VIC points.\n',
           '| corner | A1 min..max | A1 spread | A2 | A3 | f1 (MHz) | f2 (MHz) | f3 (MHz) | min stage f / DR | chain f3dB (MHz) | CMRR (dB) | PSRR (dB) |',
           '|---|---|---|---|---|---|---|---|---|---|---|---|']
    by = {}
    for r in runs:
        by.setdefault(r['corner'], []).append(r)

    def rng(rs, k, f='%.3g', s=1.0):
        v = [x['metrics'][k] * s for x in rs if x['status'] == 'ok' and k in x['metrics']]
        return '-' if not v else (f % min(v) if min(v) == max(v) else (f + '..' + f) % (min(v), max(v)))
    for c, rs in by.items():
        a = [x['metrics']['a1'] for x in rs if x['status'] == 'ok']
        out.append('| %s | %s | %.2f | %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (
            c, rng(rs, 'a1', '%.2f'), (max(a) / min(a)) if a else float('nan'), rng(rs, 'a2', '%.2f'), rng(rs, 'a3', '%.1f'), rng(rs, 'f3db1_hz', '%.0f', 1e-6),
            rng(rs, 'f3db2_hz', '%.0f', 1e-6), rng(rs, 'f3db3_hz', '%.1f', 1e-6), rng(rs, 'f3db_stage_over_dr', '%.3f'), rng(rs, 'f3db_chain_hz', '%.1f', 1e-6),
            rng(rs, 'cmrr_db', '%.1f'), rng(rs, 'psrr_db', '%.1f')))
    out.append('\nLimits: A1 >= %.1f at VIC 0.05 / 2.35 V, spread <= %.1f, per-stage f3dB >= %.1f x DR, chain >= %.0f MHz.' % (
        spec['stage1']['a1_min'], spec['stage1']['a1_spread_max'], spec['bandwidth']['stage_f3db_min_fraction_of_dr'], spec['bandwidth']['chain_f3db_min_hz'] / 1e6))
    p = os.path.join(HERE, 'results', 'ac_table.md')
    open(p, 'w').write('\n'.join(out) + '\n')
    print('\n'.join(out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
