"""hooks.py (tbl_op): node range from the RESULT v_* metrics (gate TB1: vnode_min_v >= -0.3, vnode_over_vdd_v <= 0.3)
and model_warnings counted as sim/tb1_op/hooks.py counts them.  GENERATED by sim/tbl/make_benches.py."""
import os


def post(ctx):
    v = [float(x) for k, x in ctx["measures"].items() if k.startswith("v_")]
    n = 0
    try:
        for ln in open(os.path.join(ctx["run_dir"], "ngspice.log"), errors="replace"):
            low = ln.lower()
            if "warning" in low and "comments and warnings go to log-file" not in low and "stepping failed" not in low:
                n += 1
    except OSError:
        n = float("nan")
    return {"vnode_min_v": min(v), "vnode_over_vdd_v": max(v) - float(ctx["corner"].vdd), "model_warnings": float(n)}
