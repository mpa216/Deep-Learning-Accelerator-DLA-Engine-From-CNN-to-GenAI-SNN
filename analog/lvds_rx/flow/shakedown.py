#!/usr/bin/env python3
"""shakedown.py -- PLAN_V2 build stage S1: the whole chain with the PMOS-only stage-1 variant (flag nmos_pair = 0) through TB1 and TB2 at the smoke tier.

    python3 flow/shakedown.py [--jobs 6]          (container; about 1 min)

Purpose: prove the flow runs end to end on the simplest variant and STATE THE USABLE VIC RANGE of the PMOS-only input (no gate decision: the baseline is the hybrid input).
Writes decks next to the baseline (sim/tb1_op/tb1_op_pmos.*, sim/tb2_ac/tb2_ac_pmos.*), runs both through the harness (TB1: worst7 = tt + worst5 + two resistor cross
corners, TB2: worst5), then judges every run with the SAME limits as the baseline specs and prints, per VIC, which checks fail.  -> results/shakedown_s1.json / .md
The N/P overlap and the dump-free control do not exist for this variant (no NMOS pair) and are not judged.
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
sys.path.insert(0, HERE)
import importlib.util  # noqa: E402
import common as C  # noqa: E402
from harness import runner  # noqa: E402
_sp = importlib.util.spec_from_file_location('tb1_make_deck', os.path.join(ROOT, 'sim', 'tb1_op', 'make_deck.py'))
MD = importlib.util.module_from_spec(_sp)
_sp.loader.exec_module(MD)


def make_tb2_variant():
    src = open(os.path.join(ROOT, 'sim', 'tb2_ac', 'tb2_ac.spice')).read()
    key = '.include {deck_dir}/../../sizing/sizes.spice\n'
    assert key in src
    open(os.path.join(ROOT, 'sim', 'tb2_ac', 'tb2_ac_pmos.spice'), 'w').write(
        src.replace(key, key + '.param flag_nmos_pair = 0\n').replace('* tb2_ac:', '* tb2_ac_pmos (S1 shake-down, PMOS-only stage 1, GENERATED by flow/shakedown.py):', 1))
    spec = json.load(open(os.path.join(ROOT, 'sim', 'tb2_ac', 'tb2_ac.json')))
    spec['name'] = 'tb2_ac_pmos'
    spec['deck'] = 'tb2_ac_pmos.spice'
    json.dump(spec, open(os.path.join(ROOT, 'sim', 'tb2_ac', 'tb2_ac_pmos.json'), 'w'), indent=1)


def judge(runs, limits, skip=()):
    """per VIC: list of (metric, worst value, limit) that fail, over all runs of that VIC."""
    by = {}
    for r in runs:
        v = r['params']['vic']
        d = by.setdefault(v, dict(n=0, bad=0, fails={}))
        d['n'] += 1
        if r['status'] != 'ok':
            d['bad'] += 1
            continue
        for k, lim in limits.items():
            if k in skip or k not in r['metrics']:
                continue
            x = r['metrics'][k]
            if x != x:
                continue
            if ('min' in lim and x < lim['min']) or ('max' in lim and x > lim['max']):
                f = d['fails'].setdefault(k, dict(worst=x, limit=lim, runs=0))
                f['runs'] += 1
                if abs(x) > abs(f['worst']) if 'max' in lim else x < f['worst']:
                    f['worst'] = x
    return by


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--jobs', type=int, default=6)
    a = ap.parse_args()
    MD.main('base')
    MD.main('pmos')
    make_tb2_variant()
    out = {}
    lines = ['# S1 shake-down: PMOS-only stage 1 (flag nmos_pair = 0), TB1 at worst7 and TB2 at worst5\n',
             'Generated by flow/shakedown.py. Same limits as the baseline specs (spec/gates.yaml); not a gate. N/P overlap not judged (no NMOS pair).\n']
    for name, spec_rel, corners, skip in (('tb1_op_pmos', 'sim/tb1_op/tb1_op_pmos.json', 'worst7', ('np_overlap_v',)),
                                          ('tb2_ac_pmos', 'sim/tb2_ac/tb2_ac_pmos.json', 'worst5', ())):
        recs, _ = runner.run_spec(C.path(spec_rel), jobs=a.jobs, only_corners=corners, verbose=False)
        spec = json.load(open(C.path(spec_rel)))
        res = json.load(open(C.path(os.path.dirname(spec_rel), 'results', name, 'results.json')))['runs']
        by = judge(res, spec['limits'], skip)
        out[name] = {str(v): d for v, d in sorted(by.items())}
        lines.append('\n## %s (%d runs, %d not ok)\n' % (name, len(res), sum(1 for r in res if r['status'] != 'ok')))
        lines.append('| VIC (V) | runs | not ok | failing checks (worst value, runs failing) |\n|---|---|---|---|\n')
        for v, d in sorted(by.items()):
            f = ', '.join('%s %.4g (%d)' % (k, x['worst'], x['runs']) for k, x in d['fails'].items()) or 'none'
            lines.append('| %.2f | %d | %d | %s |\n' % (v, d['n'], d['bad'], f))
        ok = [v for v, d in sorted(by.items()) if not d['fails'] and not d['bad']]
        sub = [r for r in res if '_xr' not in r['corner']]           # tt + worst5 without the two resistor cross corners
        if len(sub) != len(res):
            by5 = judge(sub, spec['limits'], skip)
            ok5 = [v for v, d in sorted(by5.items()) if not d['fails'] and not d['bad']]
            out[name + '_usable_vic_worst5'] = ok5
            lines.append('\nSame judgement on tt + worst5 only (cross corners left out): VIC points with no failing check: %s\n' % (ok5,))
            print('%s: usable VIC at tt + worst5 only: %s' % (name, ok5))
        out[name + '_usable_vic'] = ok
        lines.append('\nVIC points with no failing check: %s\n' % (ok,))
        print('%s: %d runs; usable VIC (all checks pass): %s' % (name, len(res), ok))
    C.write_json('results/shakedown_s1.json', out)
    open(C.path('results', 'shakedown_s1.md'), 'w').write(''.join(lines))
    return 0


if __name__ == '__main__':
    sys.exit(main())
