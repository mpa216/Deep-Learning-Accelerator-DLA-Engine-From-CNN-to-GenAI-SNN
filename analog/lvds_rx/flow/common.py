import yaml

ROOT = os.environ.get("LVDS_RX_ROOT") or os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "sim"))
from harness import corners as _corners  # noqa: E402


def path(*parts, root=None):
    return os.path.join(root or ROOT, *parts)


class _Loader(yaml.SafeLoader):
    """SafeLoader that also reads 3.25e9 / 1e-6 (no dot, or no exponent sign) as numbers.
    Plain PyYAML (YAML 1.1) turns those into STRINGS, which would silently break a limit."""


_Loader.add_implicit_resolver(
    "tag:yaml.org,2002:float",
    __import__("re").compile(r"^[-+]?(?:[0-9]+\.?[0-9]*|\.[0-9]+)[eE][-+]?[0-9]+$"), list("-+0123456789."))


def load_yaml(rel, root=None):
    with open(path(rel, root=root)) as f:
        return yaml.load(f, Loader=_Loader)


def load_json(rel_or_abs, root=None):
    p = rel_or_abs if os.path.isabs(rel_or_abs) else path(rel_or_abs, root=root)
    with open(p) as f:
        return json.load(f)


def write_json(rel_or_abs, obj, root=None):
    p = rel_or_abs if os.path.isabs(rel_or_abs) else path(rel_or_abs, root=root)
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as f:
        json.dump(obj, f, indent=1, sort_keys=False, default=str)
        f.write("\n")


# ------------------------------------------------------------------------------------------ hashing
def sha256_file(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _cache_path(root):
    return path(".scratch", "hashcache.json", root=root)


def sha256_file_cached(p, root=None):
    """sha256 with a (size, mtime) cache; used for the 700 MB of LUTs (cache is gitignored)."""
    st = os.stat(p)
    key = "%s|%d|%d" % (os.path.abspath(p), st.st_size, st.st_mtime_ns)
    cp = _cache_path(root)
    try:
        cache = json.load(open(cp))
    except Exception:
        cache = {}
    if key in cache:
        return cache[key]
    d = sha256_file(p)
    cache = {k: v for k, v in cache.items() if k.split("|")[0] != os.path.abspath(p)}
    cache[key] = d
    try:
        os.makedirs(os.path.dirname(cp), exist_ok=True)
        json.dump(cache, open(cp, "w"))
    except OSError:
        pass
    return d


def sha256_dir(d, root=None):
    """Hash of a directory: sha256 over sorted (relative name, file sha256) pairs; 'absent' if missing."""
    if not os.path.isdir(d):
        return "absent"
    h = hashlib.sha256()
    for name in sorted(os.listdir(d)):
        fp = os.path.join(d, name)
        if os.path.isfile(fp):
            h.update(name.encode() + b"\0" + sha256_file_cached(fp, root).encode() + b"\0")
    return h.hexdigest()


def input_hashes(root=None):
    """The three hashes carried by the sizes.spice header (PLAN_V2 section 0 rule 3):
    sizing script, LUT files, spec/spec.yaml.  `absent` when the input does not exist yet."""
    pa = load_yaml("spec/paths.yaml", root)["hash_inputs"]
    sp = path(pa["sizing_script"], root=root)
    return {
        "sizing_script": sha256_file(sp) if os.path.isfile(sp) else "absent",
        "luts": sha256_dir(path(pa["luts_dir"], root=root), root),
        "spec": sha256_file(path(pa["spec"], root=root)),
    }


def sizes_header_lines(root=None):
    """The header the sizing script must write at the top of sizes.spice (T2 imports this)."""
    h = input_hashes(root)
    return ["* sizes.spice -- generated by sizing/lvds_rx_sizing.py; DO NOT EDIT BY HAND",
            "* HASH sizing_script=%s luts=%s spec=%s" % (h["sizing_script"], h["luts"], h["spec"])]


def parse_sizes_hash(text):
    for ln in text.splitlines():
        if ln.startswith("* HASH "):
            return dict(kv.split("=", 1) for kv in ln[len("* HASH "):].split())
    return None


class StaleSizesError(RuntimeError):
    pass


def assert_fresh_sizes(sizes_path, root=None):
    """The netlist build calls this before using sizes.spice: refuses a stale or header-less file."""
    with open(sizes_path) as f:
        have = parse_sizes_hash(f.read())
    if have is None:
        raise StaleSizesError("%s has no '* HASH' header" % sizes_path)
    want = input_hashes(root)
    bad = [k for k in want if have.get(k) != want[k]]
    if bad:
        raise StaleSizesError("%s is stale: hash mismatch for %s (re-run sizing/lvds_rx_sizing.py)" %
                              (sizes_path, ", ".join(bad)))
    return True


# ------------------------------------------------------------------------------------------ spec references
def lookup(d, dotted):
    cur = d
    for part in dotted.split("."):
        cur = cur[part]
    return cur


def resolve(v, spec):
    """'$spec.a.b' -> spec['a']['b'] (recursively through lists and dicts); anything else unchanged."""
    if isinstance(v, str) and v.startswith("$spec."):
        return lookup(spec, v[len("$spec."):])
    if isinstance(v, list):
        return [resolve(x, spec) for x in v]
    if isinstance(v, dict):
        return {k: resolve(x, spec) for k, x in v.items()}
    return v


# ------------------------------------------------------------------------------------------ expected run counts
def corner_count(set_name):
    return len(_corners.get_corner_set(set_name))


def expected_runs(gate, tier):
    """Expected number of runs of a gate at a tier, computed from gates.yaml `scope` (never typed)."""
    sc = gate["scope"]
    n = corner_count(sc["corners"][tier])
    for v in (sc.get("grid") or {}).values():
        n *= int(v)
    mc = (sc.get("mc") or {}).get(tier)
    return n * (int(mc) if mc else 1)


def spec_file_problems(gate, spec_json):
    """Cross-check a testbench spec file against the frozen scope: corner set, grid counts, MC N (full tier)."""
    sc, out = gate["scope"], []
    want = sc["corners"]["full"]
    if spec_json.get("corners") != want:
        out.append("spec corners %r != gates.yaml full-tier corner set %r" % (spec_json.get("corners"), want))
    grid = spec_json.get("grid") or {}
    for k, n in (sc.get("grid") or {}).items():
        if k not in grid:
            out.append("spec grid lacks parameter %r (gates.yaml expects %d values)" % (k, n))
        elif len(grid[k]) != int(n):
            out.append("spec grid %r has %d values, gates.yaml expects %d" % (k, len(grid[k]), int(n)))
    for k in grid:
        if k not in (sc.get("grid") or {}):
            out.append("spec grid has parameter %r that gates.yaml does not list" % k)
    mc_want = (sc.get("mc") or {}).get("full")
    mc_have = (spec_json.get("mc") or {}).get("n")
    if (mc_want or None) != (mc_have or None):
        out.append("spec mc.n=%r != gates.yaml full-tier mc %r" % (mc_have, mc_want))
    return out


def spec_results_file(gate, root=None):
    """Where the harness wrote the results of the gate's spec: <spec dir>/results/<name>/results.json."""
    sp = path(gate["spec"], root=root)
    name = os.path.splitext(os.path.basename(sp))[0]
    try:
        name = json.load(open(sp)).get("name") or name
    except Exception:
        pass
    return os.path.join(os.path.dirname(sp), "results", name, "results.json")


# ------------------------------------------------------------------------------------------ decisions / ladder
def decisions(root=None):
    return load_yaml("spec/decisions.yaml", root)


def rung_taken(ladder, min_rung, root=None):
    for e in (decisions(root).get("entries") or []):
        if e.get("kind") == "rung" and e.get("ladder") == ladder and int(e.get("rung", 0)) >= int(min_rung):
            return True
    return False


# ------------------------------------------------------------------------------------------ git
def _head_from_files(root):
    """git is unusable in the container (the worktree's .git file points at a host path); read HEAD from the
    main checkout's .git, which is mounted at /foss/designs/.git."""
    try:
        top = os.path.abspath(root or ROOT)
        while top != "/" and not os.path.exists(os.path.join(top, ".git")):
            top = os.path.dirname(top)
        gd = open(os.path.join(top, ".git")).read().split("gitdir:")[1].strip()
        name = gd.rstrip("/").split("/.git/")[1]                    # worktrees/<name>
        for base in ("/foss/designs/.git", gd.split("/.git/")[0] + "/.git"):
            hp = os.path.join(base, name, "HEAD")
            if os.path.isfile(hp):
                head = open(hp).read().strip()
                if head.startswith("ref:"):
                    ref = head[4:].strip()
                    for rp in (os.path.join(base, ref), os.path.join(base, name, ref)):
                        if os.path.isfile(rp):
                            return open(rp).read().strip()[:7]
                    packed = open(os.path.join(base, "packed-refs")).read()
                    for ln in packed.splitlines():
                        if ln.endswith(" " + ref):
                            return ln.split()[0][:7]
                return head[:7]
    except Exception:
        pass
    return None


def git_state(root=None):
    def run(*a):
        try:
            r = subprocess.run(["git", "-C", root or ROOT] + list(a), capture_output=True, text=True, timeout=30)
            return r.stdout.strip() if r.returncode == 0 else ""
        except Exception:
            return ""
    commit = run("rev-parse", "--short", "HEAD")
    if commit:
        return {"commit": commit, "dirty": bool(run("status", "--porcelain", "--", "."))}
    return {"commit": _head_from_files(root) or "unknown", "dirty": None}   # dirty unknown without a working git


def is_number(x):
    return isinstance(x, (int, float)) and not isinstance(x, bool) and not math.isnan(x)
